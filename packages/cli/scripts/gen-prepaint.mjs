#!/usr/bin/env node
/* REQ-PLAT-86: regenerate packages/cli/src/init/prepaint.ts from the MAT
   output (src/theme/generated/prepaint-script.ts, itself generated by
   scripts/mat/build-prepaint-script.mjs) so the CLI inlines exactly the
   auraGlassPrepaintScript string (S-22) — never a hand-vendored copy.
   Usage: node packages/cli/scripts/gen-prepaint.mjs [--check] */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const SRC = join(here, '../../../src/theme/generated/prepaint-script.ts');
const OUT = join(here, '../src/init/prepaint.ts');

const src = readFileSync(SRC, 'utf8');
const m = /export const PREPAINT_IMPL = ("(?:[^"\\]|\\.)*");/.exec(src);
if (!m) { console.error(`gen-prepaint: PREPAINT_IMPL not found in ${SRC}`); process.exit(1); }
const impl = JSON.parse(m[1]);

const out = `/* Generated by packages/cli/scripts/gen-prepaint.mjs from
   src/theme/generated/prepaint-script.ts (MAT, S-22) — do not edit.
   auraGlassPrepaintScript is byte-identical to the string exported from
   aura-glass/theme; test/commands/init.vite.test.ts asserts no drift. */
export const PREPAINT_IMPL = ${JSON.stringify(impl)};
export const auraGlassPrepaintScript: string = PREPAINT_IMPL + '__agP(window,document,{});';
`;

if (process.argv.includes('--check')) {
  const cur = readFileSync(OUT, 'utf8');
  if (cur !== out) { console.error('gen-prepaint: src/init/prepaint.ts is stale — rerun gen-prepaint.mjs'); process.exit(1); }
  console.log('gen-prepaint: up to date');
} else {
  writeFileSync(OUT, out);
  console.log(`gen-prepaint: wrote ${OUT} (${impl.length} B impl)`);
}
