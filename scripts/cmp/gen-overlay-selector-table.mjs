#!/usr/bin/env node
/* CMP-248: generate docs/auraglass-5/migration/overlays-selectors.md —
   4.x Glass* component names → 5.0 overlay components, plus the published
   styling hooks (data-ag-part names emitted by each family's sources) and
   the css utility classes each family ships. Run:
     node scripts/cmp/gen-overlay-selector-table.mjs */
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = dirname(dirname(dirname(fileURLToPath(import.meta.url))));
const DIRS = { dialog: 'Dialog', 'alert-dialog': 'AlertDialog', sheet: 'Sheet' };
const OUT = join(ROOT, 'docs', 'auraglass-5', 'migration', 'overlays-selectors.md');

const familyDir = (dir) => join(ROOT, 'src', 'components', dir);

const sourceFiles = (dir) => {
  const out = [];
  const walk = (d) => {
    for (const e of readdirSync(d, { withFileTypes: true })) {
      const p = join(d, e.name);
      if (e.isDirectory()) {
        if (e.name !== '__tests__' && e.name !== '__fixtures__') walk(p);
      } else if (/\.(tsx?|css)$/.test(e.name) && !/\.test\./.test(e.name)) {
        out.push(p);
      }
    }
  };
  walk(familyDir(dir));
  return out;
};

/* DOM part names come from data-ag-part literals in the family's own sources
   (the contract part registry uses API names like Content; the DOM uses popup). */
const parts = (dir) => {
  const found = new Set();
  for (const f of sourceFiles(dir)) {
    for (const m of readFileSync(f, 'utf8').matchAll(/data-ag-part[=:]['"]([a-z-]+)['"]/g)) {
      found.add(m[1]);
    }
  }
  return [...found];
};

const metas = Object.entries(DIRS).map(([dir, name]) => {
  const src = readFileSync(join(familyDir(dir), `${name}.meta.ts`), 'utf8');
  const rows = [...src.matchAll(/from:\s*'([^']+)'/g)].map((m) => ({ from: m[1], to: name }));
  const cssClasses = [...new Set(
    sourceFiles(dir)
      .filter((f) => f.endsWith('.css'))
      .flatMap((f) => [...readFileSync(f, 'utf8').matchAll(/\.(ag-[a-z0-9-]+)/g)].map((m) => m[1])),
  )];
  return { dir, name, rows, parts: parts(dir), cssClasses };
});

const lines = [
  '<!-- generated by scripts/cmp/gen-overlay-selector-table.mjs — do not hand-edit -->',
  '# Overlay selector migration (4.x → 5.0)',
  '',
  'Overlay components no longer emit `glass-*` class names. Styling hooks are the',
  'published parts (`data-ag-part`) plus state attributes (`data-open`, `data-state`,',
  '`data-ag-layer`, `data-ag-thickness`, `data-ag-overlay`, `data-ag-full-height`,',
  '`data-ag-dragging`, `data-ag-animating`).',
  '',
];
for (const m of metas) {
  lines.push(`## ${m.name}`);
  lines.push('');
  lines.push('| 4.x name | 5.0 target |');
  lines.push('| --- | --- |');
  for (const r of m.rows) lines.push(`| \`${r.from}\` | \`${r.to}\` |`);
  lines.push('');
  if (m.parts.length) lines.push(`Parts: ${m.parts.map((p) => `\`[data-ag-part="${p}"]\``).join(', ')}`);
  if (m.cssClasses.length) lines.push(`Classes: ${m.cssClasses.map((c) => `\`.${c}\``).join(', ')}`);
  lines.push('');
}
mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, lines.join('\n'));
console.log(`wrote ${OUT.replace(ROOT + '/', '')} (${metas.length} metas)`);
