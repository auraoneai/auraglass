// MAT-028/040/063: TS constant emitters — tokens.ts/d.ts, presets.ts,
// material-spec.ts, motion tokens.generated.ts.
import { colorToCss } from '../color.mjs';
import { compileSpring } from '../transforms/motion-spring.mjs';
import { die, prettierFormat } from './_shared.mjs';
import { PRESET_IDS, PRESET_SCOPE, presetOverrides, presetCssText } from './preset-css.mjs';

/** Emit src/tokens/generated/tokens.ts + src/tokens/index.ts (MAT-028).
 *  REQ-MAT-22: `tokens` holds one entry per PUBLIC variable — private
 *  `--_ag-*` names are never part of the `aura-glass/tokens` surface — and the
 *  `./tokens` barrel (indexTs) exports only `tokens` plus its types. */
export async function emitTokensTs(cells) {
  const vars = [...new Set(cells.filter((c) => c.cssVar).flatMap((c) =>
    c.renderType === 'motion-spring' ? [c.cssVar, `${c.cssVar}-duration`] : [c.cssVar]))]
    .filter((v) => !v.startsWith('--_ag-'))
    .sort();
  const entries = vars.map((v) => `  ${JSON.stringify(v)}: 'var(${v})',`);
  const gen = [
    '/* @generated by scripts/tokens/build.mjs. Do not edit by hand. */',
    'export const tokens = {', ...entries, '} as const;',
    'export type TokenName = keyof typeof tokens;',
    'export type TokenPath = TokenName;',
    '',
    '/** The var(--ag-*) reference string for a public token. */',
    'export function token(path: TokenPath): string {',
    '  return tokens[path];',
    '}',
    '',
  ].join('\n');
  const index = [
    '/* @generated by scripts/tokens/build.mjs. Do not edit by hand. */',
    // Extensionless like every other src import (bundler resolution): a '.js'
    // specifier for a .ts source breaks Jest's resolver (S-35 ./tokens barrel).
    "export { tokens } from './generated/tokens';",
    "export type { TokenName, TokenPath } from './generated/tokens';",
    '',
  ].join('\n');
  return { tokensTs: await prettierFormat(gen, 'typescript'), indexTs: index };
}

/** Emit src/tokens/generated/presets.ts (MAT-063, MAT-14): the four theme
 *  presets plus each preset's cssText scoped to [data-ag-root] (the OD-16 C-2
 *  fallback: no [data-ag-theme] block reaches dist/). No persona narrative
 *  metadata in the runtime export. */
export async function emitPresetsTs(records, resolved) {
  const ids = PRESET_IDS;
  const entries = [];
  const cssEntries = [];
  for (const id of ids) {
    const t = resolved.get(`preset.${id}`);
    if (!t) die(`preset ${id} missing — expected preset.${id} token`);
    const entry = {
      id,
      name: t.name,
      canvas: {
        light: colorToCss(t.canvas.light),
        dark: colorToCss(t.canvas.dark),
      },
      neutralHue: t.neutralHue,
      accent: colorToCss(t.accent),
    };
    if (t.radiusScale !== undefined && t.radiusScale !== 1) entry.radiusScale = t.radiusScale;
    entries.push(`  ${id}: ${JSON.stringify(entry)},`);
    cssEntries.push(`  ${id}: ${JSON.stringify(presetCssText(presetOverrides(id, records, resolved)))},`);
  }
  const body = [
    '/* @generated by scripts/tokens/build.mjs. Do not edit by hand. */',
    'export type PresetId = \'aura\' | \'graphite\' | \'daylight\' | \'midnight\';',
    'export interface ThemePreset {',
    '  id: PresetId;',
    '  name: string;',
    '  canvas: { light: string; dark: string };',
    '  neutralHue: number;',
    '  accent: string;',
    '  radiusScale?: number;',
    '}',
    'export const presets: Record<PresetId, ThemePreset> = {',
    ...entries,
    '} as const;',
    `/** Selector every preset cssText is scoped to (OD-16 C-2 fallback). */`,
    `export const PRESET_SCOPE = ${JSON.stringify(PRESET_SCOPE)};`,
    '/** Per-preset cssText: sys.color.{canvas,accent,on-accent,border} as light-dark()',
    ' *  from the neutralHue ramp, radius xs..xl x radiusScale, with a no-light-dark() fallback. */',
    'export const presetCssText: Record<PresetId, string> = {',
    ...cssEntries,
    '};',
    '',
  ].join('\n');
  return prettierFormat(body, 'typescript');
}

/** Emit src/motion/tokens.generated.ts (MAT-028, MOT §4.3 shape).
 *  REQ-MAT-08: besides the flat `spring.<name>` / `spring.<name>-duration` keys,
 *  emits `spring.{snappy,smooth,fluid}.{zeta,response,duration,linear,stiffness,damping}`
 *  (response/duration in ms; stiffness = (2π/(r/1000))², damping = 2ζ√k). */
export async function emitMotionTs(records, resolved) {
  const lines = ['/* @generated by scripts/tokens/build.mjs. Do not edit by hand. */', 'export const motionTokens = {'];
  const springs = [];
  for (const [name, rec] of [...records.entries()].sort()) {
    if (!name.startsWith('sys.motion.')) continue;
    const v = resolved.get(name);
    const key = name.replace(/^sys\.motion\./, '');
    if (rec.type === 'duration') lines.push(`  ${JSON.stringify(key)}: ${v.value},`);
    else if (rec.type === 'cubicBezier') lines.push(`  ${JSON.stringify(key)}: 'cubic-bezier(${v.join(', ')})',`);
    else if (rec.type === 'motion-spring') {
      const c = compileSpring(v, name);
      lines.push(`  ${JSON.stringify(key)}: '${c.linear}',`);
      lines.push(`  ${JSON.stringify(`${key}-duration`)}: ${c.durationMs},`);
      springs.push([key.replace(/^spring\./, ''), c]);
    }
  }
  if (springs.length) {
    lines.push('  spring: {');
    for (const [s, c] of springs) {
      lines.push(`    ${JSON.stringify(s)}: {`,
        `      zeta: ${c.zeta},`,
        `      response: ${c.responseMs},`,
        `      duration: ${c.durationMs},`,
        `      linear: '${c.linear}',`,
        `      stiffness: ${+c.stiffness.toFixed(4)},`,
        `      damping: ${+c.damping.toFixed(4)},`,
        '    },');
    }
    lines.push('  },');
  }
  lines.push('} as const;', '');
  // Per-key scalar exports of the flat duration/ease keys: a consumer that
  // needs one fallback value (viewTransition reads duration.micro and
  // ease.standard) imports the scalar, so bundlers drop the whole
  // motionTokens table (REQ-PLAT-76 motion rows).
  lines.push('/** Scalar exports of the flat duration.* / ease.* keys (tree-shakable). */');
  for (const [name, rec] of [...records.entries()].sort()) {
    if (!name.startsWith('sys.motion.') || (rec.type !== 'duration' && rec.type !== 'cubicBezier')) continue;
    const key = name.replace(/^sys\.motion\./, '');
    const ident = 'motionToken' + key.split(/[.-]/).map((p) => p[0].toUpperCase() + p.slice(1)).join('');
    const v = resolved.get(name);
    lines.push(`export const ${ident} = ${rec.type === 'duration' ? v.value : `'cubic-bezier(${v.join(', ')})'`};`);
  }
  lines.push('');
  return prettierFormat(lines.join('\n'), 'typescript');
}

/** Emit src/tokens/generated/material-spec.ts (MAT-040): the sole generated TS module with
 *  raw values — docs/tests consume it; excluded from aura-glass/tokens unless imported. */
export async function emitMaterialSpecTs(records, resolved) {
  const spec = resolved.get('material.material');
  if (!spec) die('material-spec: missing material.material token');
  const body = `/* @generated by scripts/tokens/build.mjs. Do not edit by hand. */\nexport const materialSpec = ${JSON.stringify(spec, null, 2)} as const;\nexport type MaterialSpec = typeof materialSpec;\n`;
  return prettierFormat(body, 'typescript');
}

