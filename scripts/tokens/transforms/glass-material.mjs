/* Material ladder emitters (MAT-038/040/048; REQ-FIN-03): MaterialSpec -> ladders.css +
   floors.css. Surface cells key on [data-ag-surface][data-ag-variant][data-ag-thickness]
   (data-ag-material is banned — material.ts S-01). Engine scalars: --_ag-blur, --_ag-
   saturation, --_ag-brightness (light-dark), --_ag-shadow (two-layer ambient+key,
   overlay reads thick), --_ag-rim-width, --_ag-grain-opacity, --_ag-tint-alpha.
   WebKit literals are emitted on ::before only for tiers standard/enhanced and the
   no-tier default — never for lightweight, never unprefixed, never var(). */

const VARIANTS = ['regular', 'clear', 'identity'];
const BLURRED = ['regular', 'clear'];                     // identity has no backdrop filter
const THICKNESS = ['thin', 'regular', 'thick'];
const TIER_BLUR_SCALE = { standard: 1, enhanced: 1 };     // lightweight emits no literals
const dim = (v) => `${v.value}${v.unit}`;

function get(records, resolved, name) {
  const rec = records.get(name);
  if (!rec) throw new Error(`ladders: missing token ${name}`);
  return resolved.get(name);
}

/** The sole MaterialSpec (MAT-021): material.material is a single glass-material token
 *  shaped per tokens/$schema.json $defs.materialValue (variants x thickness cells,
 *  content, tint, scrim, fallbackFill, refraction). */
function materialSpec(records, resolved) {
  const spec = get(records, resolved, 'material.material');
  if (!spec?.variants?.regular || !spec?.refraction?.bezel || !spec?.scrim)
    throw new Error('ladders: material.material is not a MaterialSpec (needs variants, refraction.bezel, scrim)');
  return spec;
}

/** Cell scalars for one variant×thickness cell (no backdrop-filter var refs — the
 *  WebKit literals carry those; the generic engine path composes from these). */
const cellScalars = (spec, v, t) => {
  const c = spec.variants[v][t];
  const br = c.brightness ?? { light: 1, dark: 1 };
  return [
    `    --_ag-blur: ${dim(c.blur)};`,
    `    --_ag-saturation: ${c.saturation};`,
    `    --_ag-brightness: light-dark(${br.light}, ${br.dark});`,
    `    --_ag-grain-opacity: ${c.grain};`,
    `    --_ag-rim-width: ${dim(c.rim)};`,
    `    --_ag-shadow: var(--ag-shadow-${t}), var(--ag-shadow-${t}-key);`,
    `    --_ag-tint-alpha: ${c.alpha};`,
  ];
};

/** WebKit literal filter for a cell (constants only — MAT-034 bars var() here). */
const filterLiteral = (spec, v, t, blurPx) =>
  `blur(${blurPx}px) saturate(${spec.variants[v][t].saturation}) brightness(${spec.variants[v][t].brightness?.light ?? 1})`;

/** ladders.css — engine scalars + ::before WebKit literals + lightweight/coarse blocks. */
export function buildLadders(records, resolved) {
  const spec = materialSpec(records, resolved);
  const cell = (v, t) => spec.variants[v][t];

  const out = [
    '/* @generated by scripts/tokens/build.mjs (ladders). Do not edit. */',
    '@layer ag.compat, ag.reset, ag.tokens, ag.material, ag.components, ag.a11y;',
    '',
    '@layer ag.material {',
  ];
  // cell scalars: [data-ag-surface][data-ag-variant][data-ag-thickness]
  for (const variant of VARIANTS) {
    for (const th of THICKNESS) {
      const b = cell(variant, th).blur;
      if (b.unit === 'px' && b.value > 32) throw new Error(`blur > 32px at material.material.variants.${variant}.${th}`);
      out.push(`  [data-ag-surface][data-ag-variant="${variant}"][data-ag-thickness="${th}"] {`);
      out.push(...cellScalars(spec, variant, th));
      out.push('  }');
    }
  }
  // default-thickness rows: no [data-ag-thickness] behaves as regular
  for (const variant of VARIANTS) {
    out.push(`  [data-ag-surface][data-ag-variant="${variant}"]:not([data-ag-thickness]) {`);
    out.push(...cellScalars(spec, variant, 'regular'));
    out.push('  }');
  }
  // clear fail-safe: clear outside any declared backdrop reads the regular row
  for (const th of THICKNESS) {
    out.push(`  [data-ag-surface][data-ag-variant="clear"][data-ag-thickness="${th}"]:not(:where([data-ag-backdrop] *)) {`);
    out.push(...cellScalars(spec, 'regular', th));
    out.push('  }');
  }
  // lightweight tier: no backdrop filter ever, grain pinned low
  out.push('  [data-ag-surface][data-ag-tier="lightweight"],');
  out.push('  :where([data-ag-tier="lightweight"]) [data-ag-surface] {');
  out.push('    --_ag-blur: 0px;');
  out.push('    --_ag-grain-opacity: min(var(--_ag-grain-opacity), 0.02);');
  out.push('  }');
  // WebKit literal backdrop-filter: ::before only, constants only, standard/enhanced
  // and the no-tier default — never emitted for the lightweight tier.
  for (const variant of BLURRED) {
    for (const th of THICKNESS) {
      const b = cell(variant, th).blur;
      const base = `[data-ag-surface][data-ag-variant="${variant}"][data-ag-thickness="${th}"]`;
      const rule = `-webkit-backdrop-filter: ${filterLiteral(spec, variant, th, b.value)};`;
      out.push(`  ${base}:not(:where([data-ag-tier="lightweight"], [data-ag-tier="lightweight"] *))::before,`);
      out.push(`  :where([data-ag-tier="standard"] *, [data-ag-tier="enhanced"] *) ${base}::before,`);
      out.push(`  ${base}:where([data-ag-tier="standard"], [data-ag-tier="enhanced"])::before {`);
      out.push(`    ${rule}`);
      out.push('  }');
    }
  }
  out.push('  /* identity has no backdrop filter (MAT-038); nothing emitted for the lightweight tier */');
  out.push('');
  // coarse pointers: thick surfaces cap blur at 20px, every cell pins grain <= 0.02
  out.push('  @media (pointer: coarse) {');
  for (const variant of BLURRED) {
    out.push(`    [data-ag-surface][data-ag-variant="${variant}"][data-ag-thickness="thick"]:not(:where([data-ag-tier="lightweight"], [data-ag-tier="lightweight"] *))::before {`);
    out.push(`      -webkit-backdrop-filter: ${filterLiteral(spec, variant, 'thick', 20)};`);
    out.push('    }');
  }
  out.push('    [data-ag-surface][data-ag-thickness="thick"] {');
  out.push('      --_ag-blur: 20px;');
  out.push('    }');
  out.push('    [data-ag-surface] {');
  out.push('      --_ag-grain-opacity: min(var(--_ag-grain-opacity), 0.02);');
  out.push('    }');
  out.push('  }');
  out.push('');
  // content materials: [data-ag-content] on layer=content surfaces (AG_ATTRIBUTES)
  for (const content of Object.keys(spec.content ?? {})) {
    const cells = spec.content[content];
    if (!cells) continue;
    for (const th of THICKNESS) {
      const c = cells[th];
      out.push(`  [data-ag-surface][data-ag-content="content-${content}"][data-ag-thickness="${th}"] {`);
      out.push(`    --_ag-tint-alpha: ${c.alpha};`);
      out.push('  }');
    }
  }
  out.push('');
  out.push('  /* disabled: fill alpha scaled by --ag-state-disabled-alpha via --_ag-tint-alpha; no host opacity: (MAT-033) */');
  for (const variant of VARIANTS) {
    for (const th of THICKNESS) {
      out.push(`  [data-ag-surface][data-ag-variant="${variant}"][data-ag-thickness="${th}"][data-ag-state~="disabled"] {`);
      out.push('    --_ag-alpha: calc(var(--_ag-tint-alpha) * var(--ag-state-disabled-alpha));');
      out.push('    --_ag-blur: calc(var(--_ag-blur) * 0.6);');
      out.push('  }');
    }
  }
  out.push('}', '');
  return out.join('\n');
}

/** floors.css — OS floors + --_ag-tint-floor per [transparency][thickness][backdrop] (MAT-048). */
export function buildFloors(records, resolved, matrix = null) {
  const spec = materialSpec(records, resolved);
  const floor = (t) => get(records, resolved, `contrast.matrix.floors.${t}`);
  const scrim = spec.scrim.clear;
  const fallback = spec.fallbackFill?.alpha ?? 0.98;
  const out = [
    '/* @generated by scripts/tokens/build.mjs (floors). Do not edit. */',
    '@layer ag.compat, ag.reset, ag.tokens, ag.material, ag.components, ag.a11y;',
    '',
    '@layer ag.material {',
    '  /* --_ag-tint-floor: max solved floor across presets, schemes and variants (REQ-MAT-33 key). */',
  ];
  // matrix may be passed in by build.mjs after solving; otherwise emit authored floors
  const solved = matrix?.tintFloors ?? null;
  // Keys: transparency may sit on the surface or an ancestor; backdrop likewise
  // (REQ-FIN-03: [data-ag-transparency=x] [data-ag-surface][data-ag-thickness=y],
  //  backdrop resolved on the surface itself or an ancestor).
  for (const tr of ['glass', 'tinted', 'solid']) {
    for (const th of THICKNESS) {
      for (const bd of ['light', 'dark', 'media']) {
        const v = solved?.[tr]?.[th]?.[bd] ?? floor(th);
        const surf = `[data-ag-surface][data-ag-thickness="${th}"]`;
        out.push(`  [data-ag-transparency="${tr}"][data-ag-backdrop="${bd}"] ${surf},`);
        out.push(`  [data-ag-transparency="${tr}"] [data-ag-backdrop="${bd}"] ${surf},`);
        out.push(`  [data-ag-transparency="${tr}"] ${surf}[data-ag-backdrop="${bd}"],`);
        out.push(`  [data-ag-transparency="${tr}"][data-ag-surface][data-ag-thickness="${th}"][data-ag-backdrop="${bd}"] {`);
        out.push(`    --_ag-tint-floor: ${Math.round(v * 1000) / 1000};`);
        out.push('  }');
      }
    }
  }
  for (const th of THICKNESS) {
    for (const bd of ['light', 'dark', 'media']) {
      // contrast=more must never go below the tinted floor row (MAT-035 contract).
      const v = Math.max(solved?.more?.[th]?.[bd] ?? floor(th), solved?.tinted?.[th]?.[bd] ?? 0);
      out.push(`  [data-ag-contrast="more"][data-ag-backdrop="${bd}"] [data-ag-surface][data-ag-thickness="${th}"],`);
      out.push(`  [data-ag-contrast="more"] [data-ag-backdrop="${bd}"] [data-ag-surface][data-ag-thickness="${th}"],`);
      out.push(`  [data-ag-contrast="more"] [data-ag-surface][data-ag-thickness="${th}"][data-ag-backdrop="${bd}"] {`);
      out.push(`    --_ag-tint-floor: ${Math.round(v * 1000) / 1000};`);
      out.push('  }');
    }
  }
  out.push('}', '', '@layer ag.a11y {');
  for (const th of THICKNESS) {
    for (const variant of VARIANTS) {
      out.push(`  [data-ag-surface][data-ag-variant="${variant}"][data-ag-thickness="${th}"] {`);
      out.push(`    --_ag-floor-alpha: ${floor(th)};`);
      out.push('  }');
    }
  }
  out.push(
    '',
    '  /* Opaque fallback: forced-colors flattens the glass (blur contributes nothing);',
    '     transparency=solid raises fills to the authored floors via --_ag-tint-floor above. */',
    '  @media (forced-colors: active) {',
    '    [data-ag-surface] {',
    '      --ag-glass-opacity: 1;',
    '      --_ag-blur: 0px;',
    `      --_ag-scrim-clear: ${scrim};`,
    '    }',
    '  }',
    '',
    `  /* No backdrop-filter support: opaque fill at fallbackFill.alpha ${fallback}. */`,
    '  @supports not ((backdrop-filter: blur(1px)) or (-webkit-backdrop-filter: blur(1px))) {',
    '    [data-ag-surface] {',
    `      --_ag-alpha: ${fallback};`,
    '    }',
    '  }',
    '}',
    '',
  );
  return out.join('\n');
}
