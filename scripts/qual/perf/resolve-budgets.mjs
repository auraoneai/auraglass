#!/usr/bin/env node
/* scripts/qual/perf/resolve-budgets.mjs — REQ-QUAL-38 (QUAL). Merges the QUAL default ceilings
   (certification/thresholds.json#perf) with every stream's fragments/perf-budgets/<stream>.ts rows (loadFragments, S-50),
   fails `perf-budget-looser` on any row looser than its default, and writes the generated, git-ignored
   certification/budgets.json that L10 (surface-budget.spec.ts, grade.mjs) reads.

   Usage: node scripts/qual/perf/resolve-budgets.mjs [--root <dir>] [--out <file>] [--baseline <file>] [--scope pr|main|nightly|release]
   Exit: 0 resolved, 1 perf-budget-looser / malformed row / baseline violation, 64 usage.
   Local run is allowed (node only, no browser). Registered on L1 (certification/lanes.config.ts).

   Rows already looser on `next` when this gate landed are listed in certification/perf-budget-looser.baseline.json
   (shrink-only, owner named, expires RC-1; PRD-F §4.3 rule 3). The owner tightens or deletes the row; QUAL never raises a default. */
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { ROOT, loadQa, readJson, rel } from './lib.mjs';

export function parseArgs(argv) {
  const o = { root: ROOT, out: null, baseline: null, scope: process.env.AG_SCOPE ?? 'pr' };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i]; const v = argv[++i];
    if (v === undefined) throw new Error(`${a} needs a value`);
    if (a === '--root') o.root = resolve(v);
    else if (a === '--out') o.out = resolve(v);
    else if (a === '--baseline') o.baseline = resolve(v);
    else if (a === '--scope') o.scope = v;
    else throw new Error(`unknown argument ${a}`);
  }
  if (!['pr', 'main', 'nightly', 'release'].includes(o.scope)) throw new Error(`--scope must be pr|main|nightly|release (got ${o.scope})`);
  o.out ??= join(o.root, 'certification/budgets.json');
  o.baseline ??= join(o.root, 'certification/perf-budget-looser.baseline.json');
  return o;
}

export async function resolveCli(argv = process.argv.slice(2), log = (s) => process.stdout.write(`${s}\n`)) {
  let o;
  try { o = parseArgs(argv); } catch (e) { log(String(e.message)); return 64; }
  const budgets = await loadQa('budgets', ROOT);
  const { perf, sha256 } = budgets.loadPerfThresholds(o.root);
  const { loadFragments } = await import(pathToFileURL(join(ROOT, 'src/contracts/load-fragments.mjs')).href);
  const fragments = await loadFragments('perf-budgets', o.root);
  const res = budgets.resolveBudgets(perf, fragments);
  const baselineRows = existsSync(o.baseline) ? readJson(o.baseline) : [];
  if (!Array.isArray(baselineRows)) { log(`${rel(o.root, o.baseline)} must be a JSON array`); return 1; }
  const errors = [
    ...res.malformed.map((m) => `perf-budget-malformed: ${rel(o.root, m.file)}[${m.index}] ${m.errors.join('; ')}`),
    ...budgets.checkLooserBaseline(baselineRows, res.looser, (f) => rel(o.root, f), o.scope),
  ];
  const doc = {
    version: 1,
    $comment: 'GENERATED by scripts/qual/perf/resolve-budgets.mjs — git-ignored, never committed or hand-edited (REQ-QUAL-38).',
    thresholdsSha256: sha256,
    fragments: fragments.map((f) => ({ stream: f.stream, file: rel(o.root, f.file), rows: Array.isArray(f.value) ? f.value.length : null })),
    defaults: res.defaults,
    rows: res.rows.map((r) => ({ ...r, file: rel(o.root, r.file) })),
    looser: res.looser.map((l) => ({ ...l, file: rel(o.root, l.file) })),
    duplicates: res.duplicates.map((d) => ({ ...d, files: d.files.map((f) => rel(o.root, f)) })),
    ceilings: perf.ceilings,
  };
  mkdirSync(dirname(o.out), { recursive: true });
  writeFileSync(o.out, `${JSON.stringify(doc, null, 2)}\n`);
  log(`resolve-budgets: ${fragments.length} fragment file(s), ${res.rows.length} resolved row(s), ${res.looser.length} looser (${baselineRows.length} baselined), `
    + `${res.duplicates.length} duplicate key(s) → ${rel(o.root, o.out)}`);
  for (const d of res.duplicates.slice(0, 20)) log(`  note duplicate ${d.key}: kept ${d.kept}, dropped ${d.dropped.join(', ')}`);
  for (const e of errors) log(`  FAIL ${e}`);
  return errors.length ? 1 : 0;
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(new URL(import.meta.url).pathname)) {
  resolveCli().then((c) => { process.exitCode = c; }, (e) => { process.stderr.write(`${e?.stack ?? e}\n`); process.exitCode = 1; });
}
