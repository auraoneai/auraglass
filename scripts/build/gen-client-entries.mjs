#!/usr/bin/env node
/* REQ-PLAT-45 — generate client-entries.json.
 *
 * Maps every code export in package.json back to its src entry file
 * (dist/<p>.mjs -> src/<p>.ts | src/<p>/index.ts) and records the export
 * when the entry carries a top-level "use client" directive. The output is
 * the committed allowlist verify-pack.js checks against the built bundles.
 *
 *   node scripts/build/gen-client-entries.mjs          # write the file
 *   node scripts/build/gen-client-entries.mjs --check  # fail on drift
 *   node scripts/build/gen-client-entries.mjs --json   # print only
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = join(ROOT, 'client-entries.json');
const argv = process.argv.slice(2);
const CHECK = argv.includes('--check');
const JSON_ONLY = argv.includes('--json');

const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'));

function importTarget(spec) {
  if (typeof spec === 'string') return spec;
  return spec?.import ?? spec?.default ?? null;
}

/** src entry file for a dist path, or null when it isn't a built module. */
function srcEntryFor(distPath) {
  const rel = distPath.replace(/^\.\//, '');
  if (!rel.startsWith('dist/')) return null;
  if (!rel.endsWith('.mjs')) return null;
  const base = rel.slice('dist/'.length, -'.mjs'.length);
  for (const cand of [
    `src/${base}.ts`,
    `src/${base}.tsx`,
    `src/${base}/index.ts`,
    `src/${base}/index.tsx`,
  ]) {
    if (existsSync(join(ROOT, cand))) return cand;
  }
  return null;
}

function hasUseClient(absFile) {
  const head = readFileSync(absFile, 'utf8').slice(0, 4096);
  // first non-comment, non-'use strict' statement must be the directive
  const stripped = head
    .replace(/^\uFEFF/, '')
    .replace(/^(\s*\/\*[\s\S]*?\*\/|\s*\/\/[^\n]*\n)+/m, '');
  return /^\s*["']use client["']/.test(stripped);
}

export function computeClientEntries(root = ROOT) {
  const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
  const entries = [];
  const skipped = [];
  const seenSrc = new Set();
  for (const key of Object.keys(pkg.exports ?? {}).sort()) {
    const target = importTarget(pkg.exports[key]);
    if (!target) { skipped.push([key, 'no import target']); continue; }
    const src = srcEntryFor(target);
    if (!src) { skipped.push([key, target]); continue; }
    // type-only aliases share another export's module — record the first
    // (canonical) key only; later keys are duplicates of the same bundle.
    if (seenSrc.has(src)) { skipped.push([key, `alias of ${src}`]); continue; }
    seenSrc.add(src);
    if (hasUseClient(join(root, src))) entries.push(key);
    else skipped.push([key, `${src} (no directive)`]);
  }
  return { clientEntries: entries, skipped };
}

function main() {
  const { clientEntries, skipped } = computeClientEntries();
  const doc = {
    $schema: 'https://json-schema.org/draft/2020-12/schema',
    description:
      'PLAT-092/REQ-PLAT-45: subpath entry points whose modules carry a "use client" ' +
      'directive and therefore render only on the client. GENERATED by ' +
      'scripts/build/gen-client-entries.mjs — do not edit by hand.',
    generatedBy: 'scripts/build/gen-client-entries.mjs',
    clientEntries,
  };
  const text = JSON.stringify(doc, null, 2) + '\n';
  if (JSON_ONLY) { process.stdout.write(text); return 0; }
  if (CHECK) {
    const current = existsSync(OUT) ? JSON.parse(readFileSync(OUT, 'utf8')) : null;
    const have = new Set(current?.clientEntries ?? []);
    const want = new Set(clientEntries);
    const added = clientEntries.filter((k) => !have.has(k));
    const removed = [...have].filter((k) => !want.has(k));
    if (added.length || removed.length || !current) {
      console.error('FAIL gen-client-entries: committed client-entries.json is stale');
      added.forEach((k) => console.error(` + missing client entry ${k}`));
      removed.forEach((k) => console.error(` - stale client entry ${k}`));
      console.error('run: node scripts/build/gen-client-entries.mjs');
      return 1;
    }
    console.log(`gen-client-entries: ${clientEntries.length} entries in sync`);
    return 0;
  }
  writeFileSync(OUT, text);
  console.log(`client-entries.json written: ${clientEntries.length} entries`);
  skipped.forEach(([k, why]) => console.log(`  skip ${k} -> ${why}`));
  return 0;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === fileURLToPath(import.meta.url)) {
  process.exit(main() ?? 0);
}
