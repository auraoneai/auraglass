#!/usr/bin/env node
/* scripts/mat/dep-m-release-rows.mjs — FIN-D agent prep for REQ-FIN-57 /
   REQ-MAT-67 (release notes of the 4.2.0 and 4.3.0 minors, REQ-FIN-45).

   Generates the DEP-M row list that the 4.2.0 / 4.3.0 release notes cite,
   straight from the MAT deprecation fragment (fragments/deprecations/mat.ts,
   read through the contract loader src/contracts/load-fragments.mjs). Nothing
   in the output is hand-authored: rows are grouped by `since`, then by `kind`,
   sorted by id, and the header records the sha256 of the fragment it was
   generated from so `--check` detects a stale list.

     node scripts/mat/dep-m-release-rows.mjs [--root <repo>]
          [--versions 4.2.0,4.3.0] [--out-dir ci/mat/release-notes]
          [--check] [--json]

   Default output: <out-dir>/dep-m-<version>.md, one file per version.
   --check  exit 1 if any committed file differs from a fresh render.
   --json   print the grouped rows as JSON on stdout (for the FIN-C
            release-notes assembler); writes nothing.
   The rows stay `status: 'planned'` in the fragment until the minor ships;
   the release PR flips them, and this list is regenerated after it. */
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, '../..');
export const DEFAULT_VERSIONS = ['4.2.0', '4.3.0'];
export const DEFAULT_OUT_DIR = 'ci/mat/release-notes';
const FRAGMENT = 'fragments/deprecations/mat.ts';

const cell = (v) => {
  if (v === null || v === undefined || v === '') return '—';
  return String(v).replace(/\r?\n/g, ' ').replace(/\|/g, '\\|');
};
const code = (v) => {
  if (v === null || v === undefined || v === '') return '—';
  const s = String(v).replace(/\r?\n/g, ' ');
  return s.includes('`') ? cell(s) : '`' + s.replace(/\|/g, '\\|') + '`';
};
const countBy = (rows, key) => {
  const out = {};
  for (const r of rows) out[r[key]] = (out[r[key]] ?? 0) + 1;
  return Object.fromEntries(Object.entries(out).sort(([a], [b]) => a.localeCompare(b)));
};

/** Pure: group DEP-M rows by release version. */
export function groupRows(entries, versions = DEFAULT_VERSIONS) {
  const rows = entries.filter((e) => typeof e?.id === 'string' && e.id.startsWith('DEP-M'));
  const ids = new Set();
  const duplicates = [];
  for (const r of rows) { if (ids.has(r.id)) duplicates.push(r.id); ids.add(r.id); }
  const byVersion = Object.fromEntries(versions.map((v) => [v, []]));
  const other = [];
  for (const r of rows) (byVersion[r.since] ?? other).push(r);
  for (const v of versions) byVersion[v].sort((a, b) => a.id.localeCompare(b.id));
  return { byVersion, other: other.map((r) => ({ id: r.id, since: r.since })), duplicates, total: rows.length };
}

/** Pure: render one version's markdown list. */
export function renderVersion(version, rows, { sourceSha256, sourcePath = FRAGMENT } = {}) {
  const lines = [
    `# DEP-M rows for the aura-glass ${version} release notes`,
    '',
    '<!-- GENERATED by scripts/mat/dep-m-release-rows.mjs — do not edit by hand. -->',
    `<!-- source: ${sourcePath} sha256:${sourceSha256} -->`,
    '',
    `MAT (DEP-M) deprecations whose \`since\` is \`${version}\`: deprecated from this minor on and`,
    'removed in their `removeIn` major. The codemod column names the',
    '`@auraglass/cli migrate 4to5` transform that performs the change (— = manual migration).',
    '',
    `- Rows: ${rows.length}`,
  ];
  const kinds = countBy(rows, 'kind');
  lines.push(`- By kind: ${Object.entries(kinds).map(([k, n]) => `${k} ${n}`).join(', ') || '—'}`);
  const auto = countBy(rows, 'automation');
  lines.push(`- By automation: ${Object.entries(auto).map(([k, n]) => `${k} ${n}`).join(', ') || '—'}`);
  const status = countBy(rows, 'status');
  lines.push(`- Fragment status: ${Object.entries(status).map(([k, n]) => `${k} ${n}`).join(', ') || '—'}`);
  const removeIn = countBy(rows, 'removeIn');
  lines.push(`- Removed in: ${Object.entries(removeIn).map(([k, n]) => `${k} ${n}`).join(', ') || '—'}`);
  lines.push('');
  for (const kind of Object.keys(kinds)) {
    const group = rows.filter((r) => r.kind === kind);
    lines.push(`## ${kind} (${group.length})`, '');
    lines.push('| ID | Entry | Symbol | Replacement | Codemod | Automation | Breaking | Compat |');
    lines.push('|---|---|---|---|---|---|---|---|');
    for (const r of group) {
      lines.push(`| ${r.id} | ${code(r.entry)} | ${code(r.symbol)} | ${cell(r.replacement)} | ${code(r.codemod)} | ${cell(r.automation)} | ${cell(r.breaking)} | ${code(r.compat)} |`);
    }
    lines.push('');
  }
  return lines.join('\n');
}

async function load(root) {
  const file = join(root, FRAGMENT);
  if (!existsSync(file)) throw new Error(`dep-m-release-rows: ${FRAGMENT} not found under ${root}`);
  const { loadFragments } = await import(join(REPO, 'src/contracts/load-fragments.mjs'));
  const frags = await loadFragments('deprecations', root);
  const mat = frags.find((f) => f.stream === 'mat' && f.file.endsWith('mat.ts'));
  const entries = Array.isArray(mat?.value) ? mat.value : [];
  const sourceSha256 = createHash('sha256').update(readFileSync(file)).digest('hex');
  return { entries, sourceSha256 };
}

export async function main(argv = process.argv.slice(2)) {
  const arg = (n, d) => { const i = argv.indexOf(n); return i >= 0 ? argv[i + 1] : d; };
  const root = resolve(arg('--root', REPO));
  const versions = arg('--versions', DEFAULT_VERSIONS.join(',')).split(',').map((s) => s.trim()).filter(Boolean);
  const outDir = resolve(root, arg('--out-dir', DEFAULT_OUT_DIR));
  const { entries, sourceSha256 } = await load(root);
  const grouped = groupRows(entries, versions);
  if (grouped.duplicates.length) {
    console.error(`FAIL dep-m-release-rows: duplicate ids ${grouped.duplicates.join(', ')}`);
    return 1;
  }
  if (argv.includes('--json')) {
    process.stdout.write(JSON.stringify({ source: FRAGMENT, sourceSha256, ...grouped }, null, 2) + '\n');
    return 0;
  }
  const check = argv.includes('--check');
  let stale = 0;
  for (const v of versions) {
    const file = join(outDir, `dep-m-${v}.md`);
    const text = renderVersion(v, grouped.byVersion[v], { sourceSha256 });
    const rel = relative(root, file);
    if (check) {
      const existing = existsSync(file) ? readFileSync(file, 'utf8') : null;
      if (existing !== text) { console.error(`FAIL dep-m-release-rows: ${rel} is stale (run without --check)`); stale++; }
      continue;
    }
    mkdirSync(outDir, { recursive: true });
    writeFileSync(file, text);
    console.log(`dep-m-release-rows: wrote ${rel} (${grouped.byVersion[v].length} rows)`);
  }
  if (grouped.other.length) {
    console.log(`dep-m-release-rows: ${grouped.other.length} DEP-M row(s) outside ${versions.join('/')}: `
      + grouped.other.map((o) => `${o.id}@${o.since}`).join(', '));
  }
  if (check && !stale) console.log(`dep-m-release-rows: up to date (${grouped.total} DEP-M rows)`);
  return stale ? 1 : 0;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  // exitCode, not process.exit(): a large --json payload on a pipe must flush.
  main().then((rc) => { process.exitCode = rc; }, (e) => { console.error(e); process.exitCode = 1; });
}
