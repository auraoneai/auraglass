#!/usr/bin/env node
/* scripts/mat/compat-alias-map.mjs — REQ-MAT-21 / H03 / D-18.
   Generates tokens/compat-alias-map.json: every --glass-* name with >= 1
   reader in the 4.x snapshot (legacy/**) or the frozen consumer fixture
   (tests/fixtures/consumer-4x/cases/mat/**) mapped to an --ag-* successor or
   its frozen legacy value from tokens/legacy/4x-rendered.tokens.json.

   Successor rule (mechanical, no invented semantics): a --glass-* name maps
   to an --ag-* name only when the 5.0 contract defines a variable of the same
   measurement family AND the rendered 4.x value equals the contract value —
   e.g. --glass-space-4 = 1rem = --ag-space-4. Otherwise the name freezes at
   its rendered value so dist/compat/tokens.css keeps 4.x CSS working
   byte-for-byte. The PRD-documented --glass-motion-default -> --ag-duration-small
   is applied when the source name exists.

   A name no 4.x stylesheet declares freezes at `initial` (the guaranteed-
   invalid value the 4.x render used), tagged runtime-set-in-4x (with the files
   that write it) or undeclared-in-4x; nothing is left uncovered.
   dist/compat/tokens.css is written by the token build (emitCompat) only. */
import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync } from 'node:fs';
import { join, extname } from 'node:path';
import { execFileSync } from 'node:child_process';
import { LEGACY_COMMIT } from '../tokens/formats/compat-aliases.mjs';

const DOCUMENTED = { '--glass-motion-default': '--ag-duration-small' };

/* ---------------------------------------------------------------------------
   --codemod [--check]  (REQ-MAT-67 / D.3-22, REQ-FIN-57)
   Writes fragments/codemods/mat/css-vars.generated.ts, the `cssVars` field of
   fragments/codemods/mat.ts: every --glass-* name in
   tokens/generated/compat-alias-map.json (the vendored 4.1.0 reader set +
   4.x primitives, written by tokens:build) -> its --ag-* successor or null
   (null = deleted in 5.0; the css-vars codemod leaves a TODO_MARKER).
   - successor: the map's `successor` (MAT-075 rules in
     scripts/tokens/compat-successors.json); a successor that is a
     compat-emitted shim (`shims`, e.g. --ag-color-on-surface) is resolved to
     the public var it aliases, because the codemod must not migrate consumers
     onto a compat-only name; then the PRD-documented DOCUMENTED renames.
   - every successor must be a public 5.0 variable (src/tokens/generated/
     manifest.ts cssVar or src/contracts/tokens.ts); otherwise this exits 1.
   - no successor -> null. This resolves every name the 4.x reader scan left
     `uncovered` (no rendered 4.x value): the codemod still needs an answer.
   --check exits 1 when the committed file differs from the generated text.
   ------------------------------------------------------------------------- */
const CODEMOD_OUT = 'fragments/codemods/mat/css-vars.generated.ts';

function codemodCssVarsModule() {
  const aliasMap = JSON.parse(readFileSync('tokens/generated/compat-alias-map.json', 'utf8'));
  const { shims } = JSON.parse(readFileSync('scripts/tokens/compat-successors.json', 'utf8'));
  const publicAg = new Set();
  for (const file of ['src/tokens/generated/manifest.ts', 'src/contracts/tokens.ts']) {
    for (const m of readFileSync(file, 'utf8').matchAll(/--ag-[a-z0-9-]*[a-z0-9]/g)) publicAg.add(m[0]);
  }
  const resolveShim = (name) => {
    const seen = new Set();
    let cur = name;
    while (shims[cur] !== undefined) {
      if (seen.has(cur)) throw new Error(`compat-successors.json: shim cycle at ${cur}`);
      seen.add(cur);
      const m = /^var\((--ag-[a-z0-9-]+)\)$/.exec(String(shims[cur]).trim());
      if (!m) throw new Error(`compat-successors.json: shim ${cur} is not a single var(--ag-*) alias`);
      cur = m[1];
    }
    return cur;
  };
  const names = Object.keys(aliasMap).filter((k) => k.startsWith('--glass-')).sort();
  const lines = [];
  let mapped = 0;
  for (const name of names) {
    const raw = aliasMap[name].successor ?? DOCUMENTED[name] ?? null;
    let to = null;
    if (raw !== null) {
      to = resolveShim(raw);
      if (!/^--ag-/.test(to) || !publicAg.has(to)) {
        throw new Error(`${name} -> ${raw}${to !== raw ? ` (-> ${to})` : ''} is not a public 5.0 --ag-* variable`);
      }
      mapped += 1;
    }
    lines.push(`  '${name}': ${to === null ? 'null' : `'${to}'`},`);
  }
  const text = [
    '/* @generated by `node scripts/mat/compat-alias-map.mjs --codemod` from',
    ' * tokens/generated/compat-alias-map.json — do not edit by hand.',
    ` * ${names.length} --glass-* names: ${mapped} -> --ag-* successor, ${names.length - mapped} -> null (deleted in 5.0).`,
    ' * REQ-MAT-67 / D.3-22: the cssVars field of fragments/codemods/mat.ts. */',
    "import type { CodemodMappingFragment } from '../../../src/contracts/fragments';",
    '',
    "export const cssVars: NonNullable<CodemodMappingFragment['cssVars']> = {",
    ...lines,
    '};',
    '',
  ].join('\n');
  return { text, total: names.length, mapped };
}

if (process.argv.includes('--codemod')) {
  const { text, total, mapped } = codemodCssVarsModule();
  if (process.argv.includes('--check')) {
    const current = existsSync(CODEMOD_OUT) ? readFileSync(CODEMOD_OUT, 'utf8') : null;
    if (current !== text) {
      console.error(`compat-alias-map --codemod --check: ${CODEMOD_OUT} is stale; run node scripts/mat/compat-alias-map.mjs --codemod`);
      process.exit(1);
    }
    console.log(`compat-alias-map --codemod --check: ${CODEMOD_OUT} current (${total} names, ${mapped} successors)`);
  } else {
    writeFileSync(CODEMOD_OUT, text);
    console.log(`compat-alias-map --codemod: wrote ${CODEMOD_OUT} (${total} names, ${mapped} successors, ${total - mapped} null)`);
  }
  process.exit(0);
}

const GLASS_RE = /--glass-[a-zA-Z0-9-]+/g;
/* A name ending in '-' is a template prefix (`--glass-color-${k}`), not a
   custom property: it has no reader of its own and is never mapped. */
const isTemplatePrefix = (name) => name.endsWith('-');
/* The 4.x snapshot is the 4.1.0 source at LEGACY_COMMIT (the same commit
   tokens/legacy/4x-primitives.css and 4x-reader-set.json are vendored from),
   read straight from git so the map regenerates byte-for-byte on any checkout.
   A full legacy/src checkout on disk is used only when the commit is absent. */
const LEGACY_SRC = 'legacy/src';
const FIXTURE_DIR = 'tests/fixtures/consumer-4x/cases/mat';
const SCAN_EXT = new Set(['.ts', '.tsx', '.css', '.scss', '.js', '.jsx', '.mdx']);

function* walk(dir) {
  if (!existsSync(dir)) return;
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) yield* walk(p);
    else if (SCAN_EXT.has(extname(e.name))) yield p;
  }
}

/** [{ path, text }] of the 4.x source (src/** at LEGACY_COMMIT). */
function legacySources() {
  let names = null;
  try {
    names = execFileSync('git', ['ls-tree', '-r', LEGACY_COMMIT, '--name-only', '--', 'src'], { encoding: 'utf8', maxBuffer: 1 << 26 })
      .split('\n').filter((f) => SCAN_EXT.has(extname(f)));
  } catch { names = null; }
  if (!names) return [...walk(LEGACY_SRC)].map((path) => ({ path, text: readFileSync(path, 'utf8') }));
  const out = execFileSync('git', ['cat-file', '--batch'], { input: names.map((f) => `${LEGACY_COMMIT}:${f}`).join('\n') + '\n', maxBuffer: 1 << 28 });
  const files = [];
  for (let i = 0, n = 0; i < out.length; n++) {
    const nl = out.indexOf(10, i);
    const size = Number(out.subarray(i, nl).toString().split(' ')[2]);
    files.push({ path: `${LEGACY_SRC}/${names[n].replace(/^src\//, '')}`, text: out.subarray(nl + 1, nl + 1 + size).toString('utf8') });
    i = nl + 1 + size + 1;
  }
  return files;
}

const LEGACY = legacySources();
const SOURCES = [...LEGACY, ...[...walk(FIXTURE_DIR)].map((path) => ({ path, text: readFileSync(path, 'utf8') }))];
const readers = new Map(); // var -> file count
for (const { text } of SOURCES) {
  const seen = new Set((text.match(GLASS_RE) ?? []).filter((v) => !isTemplatePrefix(v)));
  for (const v of seen) readers.set(v, (readers.get(v) ?? 0) + 1);
}

const rendered = JSON.parse(readFileSync('tokens/legacy/4x-rendered.tokens.json', 'utf8'));
/* name -> { $value } from the frozen records (legacy.<name> with
   $extensions['ag.legacyVar'] = the 4.x property name). */
const primitives = Object.fromEntries(Object.values(rendered.legacy ?? {})
  .filter((r) => r && typeof r === 'object' && r.$extensions?.['ag.legacyVar'])
  .map((r) => [r.$extensions['ag.legacyVar'], { $value: r.$value }]));

/* Declarations harvested from every 4.x stylesheet (tokens.css primitives
   already covered; themes/*.css, component sheets etc. fill the rest).
   values.light = first non-theme or light-theme declaration; values.dark =
   dark-theme override when it differs. Values may reference other
   --glass-* names — they still resolve through this same map. */
/* custom-property values cannot contain ';' and may span lines
   (e.g. hsl(\n 217 91% 60%\n)) — capture up to ';' or a closing '}'. */
const DECL_RE = /(--glass-[a-zA-Z0-9-]+)\s*:\s*([^;}]+?)\s*(?:;|(?=\s*}))/g;
const decls = new Map(); // name -> { light?: string, dark?: string }
for (const { path: file, text } of LEGACY) {
  if (extname(file) !== '.css') continue;
  const dark = /dark/.test(file);
  const light = !dark;
  for (const m of text.matchAll(DECL_RE)) {
    const rec = decls.get(m[1]) ?? {};
    if (light && rec.light === undefined) rec.light = m[2].trim();
    if (dark && rec.dark === undefined) rec.dark = m[2].trim();
    decls.set(m[1], rec);
  }
}

function frozenValue(name) {
  const prim = primitives[name]?.$value;
  const d = decls.get(name) ?? {};
  if (prim !== undefined && d.dark !== undefined && d.dark !== (d.light ?? prim)) {
    return { light: d.light ?? prim, dark: d.dark };
  }
  const single = prim ?? d.light;
  if (single !== undefined && d.dark !== undefined && d.dark !== single) return { light: single, dark: d.dark };
  return single !== undefined ? single : (d.dark !== undefined ? { light: d.dark } : null);
}

/* 5.0 contract values for the mechanical successor check. */
const AG_SPACE_PX = { '0': 0, '1': 4, '2': 8, '3': 12, '4': 16, '5': 20, '6': 24, '8': 32, '10': 40, '12': 48, '16': 64 };
const AG_RADIUS_PX = { xs: 6, sm: 10, md: 14, lg: 20, xl: 28, full: 9999 };
const toPx = (v) => {
  if (/^-?\d+(\.\d+)?px$/.test(v)) return parseFloat(v);
  if (/^-?\d+(\.\d+)?rem$/.test(v)) return parseFloat(v) * 16;
  if (v === '0') return 0;
  return null;
};
function successor(name, legacyValue) {
  if (DOCUMENTED[name]) return DOCUMENTED[name];
  const space = /^--glass-space-(\d+)$/.exec(name);
  if (space && space[1] in AG_SPACE_PX) {
    const px = toPx(legacyValue ?? '');
    if (px !== null && px === AG_SPACE_PX[space[1]]) return `--ag-space-${space[1]}`;
  }
  const radius = /^--glass-radius-(xs|sm|md|lg|xl|full)$/.exec(name);
  if (radius) {
    const px = toPx(legacyValue ?? '');
    if (px !== null && px === AG_RADIUS_PX[radius[1]]) return `--ag-radius-${radius[1]}`;
  }
  return null;
}

/** 4.x files that write `name` at runtime (style object key, setProperty, or a
    `name: value` declaration inside TS/TSX css text). */
function runtimeSetters(name) {
  const esc = name.replace(/[-]/g, '\\-');
  const re = new RegExp(`['"\`]${esc}['"\`]\\s*[:,]|setProperty\\(\\s*['"\`]${esc}['"\`]|(^|[\\s;{])${esc}\\s*:\\s*[^;)]`, 'm');
  return LEGACY.filter((f) => /\.(tsx?|jsx?)$/.test(f.path) && re.test(f.text)).map((f) => f.path).sort();
}

const entries = {};
let mapped = 0, frozen = 0, uncovered = 0, runtimeSet = 0, undeclared = 0;
for (const name of [...readers.keys()].sort()) {
  const prim = primitives[name]?.$value;
  const succ = successor(name, typeof prim === 'string' ? prim : undefined);
  const fv = frozenValue(name);
  if (succ) { entries[name] = { successor: succ, readers: readers.get(name) }; mapped += 1; }
  else if (fv !== null) { entries[name] = { frozenValue: fv, readers: readers.get(name) }; frozen += 1; }
  else {
    /* Declared nowhere in 4.x CSS: the 4.x render is the guaranteed-invalid
       value — readers fall back to their var() fallback, or the component sets
       the name at runtime on its own element (style key / setProperty /
       CSS-in-JS). Freezing it as `initial` (the guaranteed-invalid value)
       reproduces both byte-for-byte; dist/compat/tokens.css declares nothing
       for it (undeclared === initial), so 4.x rendering is unchanged. */
    const runtime = runtimeSetters(name);
    entries[name] = {
      frozenValue: 'initial',
      frozenAs: runtime.length ? 'runtime-set-in-4x' : 'undeclared-in-4x',
      readers: readers.get(name),
      ...(runtime.length ? { setBy: runtime } : {}),
    };
    frozen += 1;
    if (runtime.length) runtimeSet += 1; else undeclared += 1;
  }
}

const map = {
  $schema: 'auraglass/compat-alias-map/v1',
  description: 'H03 (D-18): every --glass-* name with a 4.x reader -> --ag-* successor or frozen value. Generated by scripts/mat/compat-alias-map.mjs; do not hand-edit.',
  generatedFrom: { readers: [`${LEGACY_SRC} (git ${LEGACY_COMMIT}:src)`, FIXTURE_DIR], values: 'tokens/legacy/4x-rendered.tokens.json' },
  counts: { total: readers.size, mapped, frozen, uncovered, runtimeSet, undeclared },
  entries,
};
const MAP_OUT = 'tokens/compat-alias-map.json';
const mapText = JSON.stringify(map, null, 1) + '\n';
if (process.argv.includes('--check')) {
  // fail when the committed map differs from a fresh generation, or anything is uncovered
  const current = existsSync(MAP_OUT) ? readFileSync(MAP_OUT, 'utf8') : null;
  if (current !== mapText) {
    console.error(`compat-alias-map --check: ${MAP_OUT} is stale; run node scripts/mat/compat-alias-map.mjs`);
    process.exit(1);
  }
  if (uncovered) { console.error(`compat-alias-map --check: ${uncovered} names uncovered`); process.exit(1); }
  console.log(`compat-alias-map --check: ${MAP_OUT} current (${readers.size} names, 0 uncovered)`);
  process.exit(0);
}
mkdirSync('tokens', { recursive: true });
writeFileSync(MAP_OUT, mapText);

/* dist/compat/tokens.css has one writer: the token build's emitCompat
   (scripts/tokens/formats/compat-aliases.mjs, REQ-MAT-21). */
console.log(`compat-alias-map: ${readers.size} names (${mapped} successors, ${frozen} frozen [${runtimeSet} runtime-set, ${undeclared} undeclared in 4.x], ${uncovered} uncovered)`);
