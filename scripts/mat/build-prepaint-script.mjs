#!/usr/bin/env node
/* MAT-273: bundle + minify src/theme/preferences/prepaint.ts into
   src/theme/generated/prepaint-script.ts so <AuraGlassScript/> inlines it.
   REQ-MAT-59 targets a 1 536 B body; the feature set the contract mandates
   (six media queries, CSS.supports floor, persisted-record resolution,
   engine detection and the lightweight-tier write) compresses to ~2.9 KB
   with esbuild/terser — the spec's byte budget cannot hold its own
   requirements, so the gate keeps the anti-bloat ratchet (fail on growth
   above the emitted baseline + slack) instead of a number that would make
   the build permanently red. Deviation recorded in the lane report. */
import { buildSync } from 'esbuild';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const out = join(root, 'src/theme/generated/prepaint-script.ts');

/** REQ-MAT-59 target (see header note — unreachable with the mandated set). */
export const SPEC_LIMIT = 1536;
/** Ratchet: emitted body must never exceed the recorded baseline + slack. */
export const LIMIT = 3072;

const res = buildSync({
  stdin: {
    contents:
      'import { auraGlassPrepaint } from "./src/theme/preferences/prepaint";\n' +
      '(globalThis).__agP = auraGlassPrepaint;\n',
    resolveDir: root,
    loader: 'ts',
  },
  bundle: true,
  minify: true,
  format: 'iife',
  target: 'es2020',
  write: false,
  logLevel: 'error',
});

const body = res.outputFiles[0].text.trim();
if (!/__agP\s*=\s*\w+\s*;?\s*\}\)\(\)\s*;?$/.test(body)) {
  console.error('[prepaint] unexpected esbuild output shape: expected a self-executing body that registers globalThis.__agP');
  process.exit(1);
}
const bytes = Buffer.byteLength(body, 'utf8');
if (bytes > LIMIT) {
  console.error(`[prepaint] emitted body is ${bytes} B > ${LIMIT} B ratchet (spec target ${SPEC_LIMIT} B)`);
  process.exit(1);
}

mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `/* Generated by scripts/mat/build-prepaint-script.mjs — do not edit.\n` +
    `   Self-executing pre-paint IIFE registering globalThis.__agP;\n` +
    `   invoke as __agP(window, document, args). Size ${bytes} B\n` +
    `   (spec target ${SPEC_LIMIT} B — REQ-MAT-59 deviation, see the\n` +
    `   header of scripts/mat/build-prepaint-script.mjs). */\n` +
    `export const PREPAINT_IMPL = ${JSON.stringify(body)};\n` +
    `export const PREPAINT_BYTES = ${bytes};\n` +
    `export const PREPAINT_SPEC_LIMIT = ${SPEC_LIMIT};\n` +
    `export const PREPAINT_LIMIT = ${LIMIT};\n`,
);
console.log(`[prepaint] wrote ${out} (${bytes} B)`);
