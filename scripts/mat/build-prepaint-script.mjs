#!/usr/bin/env node
/* MAT-273 / REQ-MAT-59: bundle + minify src/theme/preferences/prepaint.ts
   (with resolve.ts and engine.ts, the store's own resolver and engine
   detector) into src/theme/generated/prepaint-script.ts so <AuraGlassScript/>
   inlines it.

   Size gate. REQ-MAT-59 sets the body budget at SPEC_LIMIT = 1 536 B. The
   mandated feature set (six media queries, CSS.supports floor, persisted +
   app resolution through the shared resolver, the shared engine detector,
   tier + unknown-engine cap, --ag-glass-opacity) does not fit it: this body
   is the measured minimum this build reaches (see PREPAINT_BYTES), and raising
   the budget is an owner-approved contract change only (FIN-D D.3-35; the
   request is carried in the D.3-35 PR as an owner action, not decided here).
   Until that decision LIMIT is the enforced ceiling: it was tightened from the
   former 3 072 B ratchet to 2 304 B and may only go down. The build fails above
   LIMIT, and prints the SPEC_LIMIT gap on every run.

   Modes:
     (none)    build, gate, write the generated module
     --check   build in memory, gate, exit 1 if the generated module differs
     --print   build in memory, print {"body","bytes"} JSON to stdout (drift test) */
import { buildSync } from 'esbuild';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const out = join(root, 'src/theme/generated/prepaint-script.ts');

/** REQ-MAT-59 budget for the minified body. */
export const SPEC_LIMIT = 1536;
/** Enforced ceiling until the owner decides on SPEC_LIMIT; only ever lowered. */
export const LIMIT = 2304;

/* Internal signal fields (OsSignals / CapabilitySignals.backdropFilter) never
   leave the bundle, so they are renamed. Persisted/app keys, PaintResult keys
   and navigator fields (saveData, deviceMemory) are read from outside and are
   never mangled. */
const MANGLE = /^(forcedColors|contrastMore|reducedTransparency|reducedMotion|schemeDark|coarsePointer|backdropFilter)$/;

export const buildPrepaintBody = () => {
  const res = buildSync({
    stdin: {
      contents:
        'import { auraGlassPrepaint } from "./src/theme/preferences/prepaint";\n' +
        '(globalThis).__agP = auraGlassPrepaint;\n',
      resolveDir: root,
      loader: 'ts',
    },
    bundle: true,
    minify: true,
    mangleProps: MANGLE,
    format: 'iife',
    target: 'es2020',
    write: false,
    logLevel: 'error',
  });
  const body = res.outputFiles[0].text.trim();
  if (!/__agP\s*=\s*\w+\s*;?\s*\}\)\(\)\s*;?$/.test(body)) {
    throw new Error('[prepaint] unexpected esbuild output shape: expected a self-executing body that registers globalThis.__agP');
  }
  return { body, bytes: Buffer.byteLength(body, 'utf8') };
};

const render = (body, bytes) =>
  `/* Generated by scripts/mat/build-prepaint-script.mjs — do not edit.\n` +
  `   Self-executing pre-paint IIFE registering globalThis.__agP;\n` +
  `   invoke as __agP(window, document, args). Size ${bytes} B\n` +
  `   (REQ-MAT-59 budget ${SPEC_LIMIT} B; enforced ceiling ${LIMIT} B pending the\n` +
  `   owner decision recorded in scripts/mat/build-prepaint-script.mjs). */\n` +
  `export const PREPAINT_IMPL = ${JSON.stringify(body)};\n` +
  `export const PREPAINT_BYTES = ${bytes};\n` +
  `export const PREPAINT_SPEC_LIMIT = ${SPEC_LIMIT};\n` +
  `export const PREPAINT_LIMIT = ${LIMIT};\n`;

const main = () => {
  const mode = process.argv[2] ?? '';
  let built;
  try {
    built = buildPrepaintBody();
  } catch (err) {
    console.error(err instanceof Error ? err.message : String(err));
    return 1;
  }
  const { body, bytes } = built;
  if (mode === '--print') {
    process.stdout.write(`${JSON.stringify({ body, bytes })}\n`);
    return 0;
  }
  if (bytes > LIMIT) {
    console.error(`[prepaint] emitted body is ${bytes} B > ${LIMIT} B ceiling (REQ-MAT-59 budget ${SPEC_LIMIT} B)`);
    return 1;
  }
  if (bytes > SPEC_LIMIT) {
    console.warn(`[prepaint] body ${bytes} B exceeds the REQ-MAT-59 budget of ${SPEC_LIMIT} B by ${bytes - SPEC_LIMIT} B (owner decision pending; MAT-59 stays open)`);
  }
  const text = render(body, bytes);
  if (mode === '--check') {
    let cur = '';
    try { cur = readFileSync(out, 'utf8'); } catch { /* missing => drift */ }
    if (cur !== text) {
      console.error('[prepaint] src/theme/generated/prepaint-script.ts is stale: run node scripts/mat/build-prepaint-script.mjs');
      return 1;
    }
    console.log(`[prepaint] generated module in sync (${bytes} B)`);
    return 0;
  }
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, text);
  console.log(`[prepaint] wrote ${out} (${bytes} B)`);
  return 0;
};

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  process.exitCode = main();
}
