#!/usr/bin/env node
/* scripts/docs/gen-component-docs.mjs — PLAT-378 (REQ-PLAT-100, REQ-FIN-43).
   Generated component reference, driven by every src/**\/<Name>.meta.ts (S-31)
   whose name is a value export of its entry (S-35) in the types program of
   gen-props.mjs (the packed d.ts when a tarball is present) and, with
   --snapshot, in the runtime export snapshot of scripts/release/export-snapshot.mjs.
   A meta whose name is not exported gets no page.

   Per component:
     apps/docs/generated/components/<slug>.md  full page source (git-ignored; the
       docs app routes it to /components/<slug>): import line, examples from
       apps/docs/examples/<slug>/*.tsx, props (name, type, default, TSDoc),
       variants, data-ag-part and data-state tables, keyboard (APG), RSC status,
       size budget + measured size / perf grade as claims, 4.x Replaces list and
       the MigrationRow.selectors table.
     apps/docs/public/components/<slug>.md     committed agent-facing page: same
       props and parts sets plus one minimal example.
     apps/docs/generated/props.json            gen-props rows per component.

     node scripts/docs/gen-component-docs.mjs [--check] [--tsdoc] [--tsdoc-report <path>]
       [--tarball <tgz>] [--require-packed] [--snapshot <export-snapshot.json>]
   --check writes nothing and exits 1 when the committed public pages differ
   from what the metas and types produce (changed, missing or stale files).
   --tsdoc exits 1 when a tier misses its TSDoc threshold (T0/T1 100 %, T2
   ≥95 % before RC and 100 % from RC) after the expiring baseline
   scripts/integration/baselines/tsdoc-coverage.json, or when a baseline row
   is stale/expired. --tsdoc-report writes every undocumented prop as a
   candidate baseline row. */
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { keyboardFor } from './apg-keyboard.mjs';
import { extractProps, resolveTypesSource, serializeProps } from './gen-props.mjs';
import { loadMetas, slugify } from './load-metas.mjs';
import { CLAIMS_PATH, GENERATED_DIR } from './paths.mjs';

const ROOT_DEFAULT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
export const PUBLIC_DIR = 'apps/docs/public/components';
export const PAGES_DIR = `${GENERATED_DIR}/components`;
export const EXAMPLES_DIR = 'apps/docs/examples';
const HEADER = (file) => `<!-- @generated by scripts/docs/gen-component-docs.mjs (REQ-PLAT-100) from ${file}. Do not edit; run node scripts/docs/gen-component-docs.mjs. -->`;

/** Size / perf claim ids resolved from apps/docs/generated/claims.json (gen-claims, PLAT-104). */
export const claimIds = (slug) => ({ size: `component-size-gzip-kb:${slug}`, perf: `component-perf-grade:${slug}` });

const importPath = (entry) => (entry === '.' ? 'aura-glass' : `aura-glass/${entry.replace(/^\.\//, '')}`);
const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const code = (s) => `\`${cell(s).replace(/`/g, "'")}\``;
const table = (head, rows) => [`| ${head.join(' | ')} |`, `| ${head.map(() => '---').join(' | ')} |`, ...rows.map((r) => `| ${r.join(' | ')} |`)].join('\n');
const RSC_TEXT = {
  server: 'server-safe: renders in React Server Components without a client boundary',
  client: "client component: ships 'use client' and must be rendered from a client boundary or passed as children",
  mixed: 'mixed: server-safe root with client-only parts',
};

/** Examples for a slug: apps/docs/examples/<slug>/*.tsx, sorted; `minimal`/`basic` first when present. */
export function collectExamples(root, slug) {
  const dir = join(root, EXAMPLES_DIR, slug);
  if (!existsSync(dir) || !statSync(dir).isDirectory()) return [];
  const rank = (n) => (n === 'minimal' ? 0 : n === 'basic' ? 1 : 2);
  return readdirSync(dir).filter((f) => f.endsWith('.tsx')).map((f) => ({
    name: f.replace(/\.tsx$/, ''), path: `${EXAMPLES_DIR}/${slug}/${f}`, source: readFileSync(join(dir, f), 'utf8').trimEnd(),
  })).sort((a, b) => rank(a.name) - rank(b.name) || a.name.localeCompare(b.name));
}

function readSnapshot(path) {
  if (!path) return null;
  const snap = JSON.parse(readFileSync(path, 'utf8'));
  if (!snap.entries || typeof snap.entries !== 'object') throw new Error(`${path}: not an export-snapshot.mjs snapshot (no entries)`);
  return snap;
}

/**
 * Build the whole reference in memory.
 * @returns {{ components, skipped, conflicts, props, typesSource }}
 */
export function buildReference({ root = ROOT_DEFAULT, tarball = null, requirePacked = false, snapshotPath = null } = {}) {
  const { metas, conflicts } = loadMetas(root);
  const snapshot = readSnapshot(snapshotPath);
  const source = resolveTypesSource({ root, tarball, requirePacked });
  let extracted;
  try {
    extracted = extractProps({ root, source, wanted: metas.map((m) => ({ name: m.meta.name, entry: m.meta.entry })) });
  } finally { source.cleanup(); }
  const components = []; const skipped = [];
  for (const { meta, file } of metas) {
    if (!extracted.exported[meta.name]) { skipped.push({ name: meta.name, file, reason: `not a value export of ${importPath(meta.entry)}` }); continue; }
    if (snapshot) {
      const runtime = snapshot.entries[meta.entry]?.runtime ?? [];
      if (!runtime.includes(meta.name)) { skipped.push({ name: meta.name, file, reason: `not in the runtime export snapshot of ${meta.entry}` }); continue; }
    }
    const slug = slugify(meta.name);
    components.push({ name: meta.name, slug, file, meta, props: extracted.props[meta.name] ?? [], examples: collectExamples(root, slug) });
  }
  const props = Object.fromEntries(components.map((c) => [c.name, c.props]));
  return { components, skipped, conflicts, props, typesSource: source.describe };
}

function propsTable(rows) {
  if (!rows.length) return '_No public props beyond the inherited HTML attributes._';
  return table(['Prop', 'Type', 'Default', 'Description'], rows.map((r) => [
    code(r.name + (r.required ? '' : '?')), code(r.type), r.default ? code(r.default) : '—',
    cell([r.deprecated !== null ? `**Deprecated.** ${r.deprecated}`.trim() : '', r.description ?? ''].filter(Boolean).join(' ')) || '—',
  ]));
}
const partsTable = (parts) => (parts.length
  ? table(['Part', 'Selector'], parts.map((p) => [code(p), code(`[data-ag-part="${p}"]`)]))
  : '_No parts declared._');
const statesTable = (states) => (states.length ? table(['State'], states.map((s) => [code(s)])) : '_No states declared._');

/** Minimal example for the public page: the first example, or an explicit pending line. */
function exampleBlock(c, all) {
  const list = all ? c.examples : c.examples.slice(0, 1);
  if (!list.length) return `_Example pending: no \`${EXAMPLES_DIR}/${c.slug}/*.tsx\` yet._`;
  return list.map((e) => `${all ? `### ${e.name}\n\n` : ''}\`\`\`tsx\n${e.source}\n\`\`\``).join('\n\n');
}

/** Agent-facing apps/docs/public/components/<slug>.md (committed; checked by --check). */
export function renderPublic(c) {
  const m = c.meta;
  return [
    HEADER(c.file),
    '',
    `# ${c.name}`,
    '',
    '```ts',
    `import { ${c.name} } from '${importPath(m.entry)}';`,
    '```',
    '',
    `Tier ${m.tier} · RSC ${m.rsc}${m.apg ? ` · APG ${m.apg}` : ''}`,
    '',
    '## Props',
    '',
    propsTable(c.props),
    '',
    '## Parts',
    '',
    partsTable(m.parts),
    '',
    '## States',
    '',
    statesTable(m.states ?? []),
    '',
    '## Example',
    '',
    exampleBlock(c, false),
    '',
  ].join('\n');
}

function claimText(claims, id) {
  const v = claims?.[id];
  return v && v.value != null ? `${v.value}${v.unit ? ` ${v.unit}` : ''} (claim \`${id}\`)` : `pending (claim \`${id}\`)`;
}

/** Full page source apps/docs/generated/components/<slug>.md. */
export function renderPage(c, { claims = null } = {}) {
  const m = c.meta;
  const kb = keyboardFor(m.apg);
  const ids = claimIds(c.slug);
  const variants = Object.entries(m.variants ?? {});
  const migration = m.migration ?? [];
  const selectors = migration.flatMap((row) => Object.entries(row.selectors ?? {}).map(([from, to]) => [row.from, from, to]));
  const keyboard = kb.rows === null
    ? `_Keyboard table pending: no APG keyboard rows for \`${kb.pattern}\` in scripts/docs/apg-keyboard.mjs._`
    : kb.rows.length
      ? `${table(['Key', 'Action'], kb.rows.map(([k, a]) => [code(k), cell(a)]))}\n\nPattern: [${kb.pattern}](${kb.url})`
      : kb.pattern ? `No keyboard interaction (APG \`${kb.pattern}\`).` : 'Not an interactive APG pattern.';
  return [
    HEADER(c.file),
    '',
    `# ${c.name}`,
    '',
    '```ts',
    `import { ${c.name} } from '${importPath(m.entry)}';`,
    '```',
    '',
    `- Tier: ${m.tier}${typeof m.flagship === 'number' ? ` (flagship #${m.flagship})` : ''}`,
    `- Owner: ${m.owner}`,
    `- RSC: ${m.rsc} — ${RSC_TEXT[m.rsc] ?? 'unspecified'}`,
    m.material ? `- Material layer: ${m.material.layer}${m.material.refractionEligible ? ' (refraction eligible)' : ''}` : null,
    '',
    '## Examples',
    '',
    exampleBlock(c, true),
    '',
    '## Props',
    '',
    propsTable(c.props),
    '',
    '## Variants',
    '',
    variants.length ? table(['Prop', 'Values'], variants.map(([k, v]) => [code(k), v.map(code).join(', ')])) : '_No variants declared._',
    '',
    '## Parts',
    '',
    partsTable(m.parts),
    '',
    '## States',
    '',
    statesTable(m.states ?? []),
    '',
    '## Keyboard',
    '',
    keyboard,
    '',
    '## Size and performance',
    '',
    `- Size budget: ${typeof m.budgetKb === 'number' ? `${m.budgetKb} KB gzip (meta budgetKb)` : 'none declared'}`,
    `- Measured size: ${claimText(claims, ids.size)}`,
    `- Perf grade: ${claimText(claims, ids.perf)}`,
    '',
    '## Replaces (4.x)',
    '',
    migration.length
      ? table(['4.x export', 'Codemod automation', 'Compat adapter'], migration.map((r) => [code(r.from), cell(r.automation), r.compat ? 'yes' : 'no']))
      : '_Replaces no 4.x export._',
    '',
    '## Selector migration',
    '',
    selectors.length ? table(['4.x export', '4.x selector', '5.0 selector'], selectors.map(([f, a, b]) => [code(f), code(a), code(b)])) : '_No 4.x selectors to migrate._',
    '',
  ].filter((l) => l !== null).join('\n');
}

/** Parse the Prop / Part names out of a rendered page (used by --check consumers and docs-pages.test.ts). */
export function sectionNames(md, heading) {
  const start = md.indexOf(`\n## ${heading}\n`);
  if (start < 0) return null;
  const rest = md.slice(start + heading.length + 5);
  const end = rest.search(/\n## /);
  const body = end < 0 ? rest : rest.slice(0, end);
  return body.split('\n').filter((l) => /^\| `/.test(l)).map((l) => /^\| `([^`]*)`/.exec(l)[1].replace(/\?$/, ''));
}

const PROMOTED_TIERS = ['T0', 'T1'];
/** TSDoc threshold for a tier at a package version: T0/T1 100 %; T2 ≥95 % before RC, 100 % at RC/GA. */
export function tsdocThreshold(tier, version) {
  if (PROMOTED_TIERS.includes(tier)) return 1;
  if (tier === 'T2') return /-(alpha|beta)\b/.test(version) ? 0.95 : 1;
  return null; // preview: reported, not gated
}

/** Per-tier TSDoc coverage of the generated props. A prop listed in `baseline`
    (rows { prop: 'Name.prop', owner, reqFin, expires }) is excused while the row
    is unexpired; a baseline row whose prop is now documented or gone is stale
    and fails, as does an expired row (§4.3 rule 3 expiring baseline). */
export function tsdocCoverage(components, version, baseline = []) {
  const excused = new Map(baseline.map((r) => [r.prop, r]));
  const tiers = {};
  const seen = new Set();
  for (const c of components) {
    const t = (tiers[c.meta.tier] ??= { documented: 0, excused: 0, total: 0, undocumented: [] });
    for (const p of c.props) {
      const id = `${c.name}.${p.name}`;
      t.total++;
      if (p.description) { t.documented++; continue; }
      seen.add(id);
      const row = excused.get(id);
      if (row && !baselineExpired(row, version)) t.excused++;
      else t.undocumented.push(id);
    }
  }
  const failures = [];
  for (const [tier, t] of Object.entries(tiers)) {
    t.threshold = tsdocThreshold(tier, version);
    t.ratio = t.total ? (t.documented + t.excused) / t.total : 1;
    if (t.threshold !== null && t.ratio < t.threshold) failures.push({ tier, ratio: t.ratio, threshold: t.threshold, undocumented: t.undocumented });
  }
  const stale = baseline.filter((r) => !seen.has(r.prop)).map((r) => r.prop);
  const expired = baseline.filter((r) => seen.has(r.prop) && baselineExpired(r, version)).map((r) => r.prop);
  return { tiers, failures, stale, expired, ok: failures.length === 0 && stale.length === 0 && expired.length === 0 };
}

/** An `expires: 'RC-1'` row expires once the package version is 5.x.y-rc.N or a GA version. */
export function baselineExpired(row, version) {
  if (row.expires !== 'RC-1') return true; // unknown expiry never excuses
  return !/-(alpha|beta)\b/.test(version);
}

export const TSDOC_BASELINE = 'scripts/integration/baselines/tsdoc-coverage.json';
/** The expiring TSDoc baseline (FIN-A file); null when it does not exist. */
export function readTsdocBaseline(root) {
  const p = join(root, TSDOC_BASELINE);
  return existsSync(p) ? JSON.parse(readFileSync(p, 'utf8')) : null;
}

/** Candidate baseline rows for every currently undocumented prop of a gated tier (written by --tsdoc-report). */
export const tsdocReportRows = (components) => components.filter((c) => tsdocThreshold(c.meta.tier, '5.0.0') !== null)
  .flatMap((c) => c.props.filter((p) => !p.description)
    .map((p) => ({ prop: `${c.name}.${p.name}`, tier: c.meta.tier, owner: c.meta.owner, meta: c.file, expires: 'RC-1' })));

/** Compare rendered public pages with <root>/apps/docs/public/components. */
export function diffPublic(root, rendered) {
  const dir = join(root, PUBLIC_DIR);
  const onDisk = existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith('.md')) : [];
  const drift = [];
  for (const [file, text] of rendered) {
    const p = join(dir, file);
    if (!existsSync(p)) drift.push({ file, kind: 'missing' });
    else if (readFileSync(p, 'utf8') !== text) drift.push({ file, kind: 'changed' });
  }
  for (const f of onDisk) if (!rendered.has(f)) drift.push({ file: f, kind: 'stale' });
  return drift.sort((a, b) => a.file.localeCompare(b.file));
}

export function run({ root = ROOT_DEFAULT, check = false, tsdoc = false, tsdocReport = null, tarball = null, requirePacked = false, snapshotPath = null, log = console.log, error = console.error } = {}) {
  if (!existsSync(join(root, 'build/exports.manifest.json')) && !tarball) {
    error('gen-component-docs: build/exports.manifest.json missing (run node scripts/build/generate-exports.mjs)');
    return 1;
  }
  const ref = buildReference({ root, tarball, requirePacked, snapshotPath });
  const version = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).version;
  const rendered = new Map(ref.components.map((c) => [`${c.slug}.md`, renderPublic(c)]));
  for (const s of ref.skipped) log(`gen-component-docs: no page for ${s.name} (${s.file}): ${s.reason}`);
  for (const c of ref.conflicts) log(`gen-component-docs: duplicate meta '${c.name}': documenting ${c.kept}, not ${c.dropped}`);
  const baseline = readTsdocBaseline(root);
  const coverage = tsdocCoverage(ref.components, version, baseline ?? []);
  for (const [tier, t] of Object.entries(coverage.tiers).sort()) {
    log(`gen-component-docs: TSDoc ${tier} ${t.documented}/${t.total} documented, ${t.excused} baselined (${(t.ratio * 100).toFixed(1)} %)`
      + `${t.threshold === null ? '' : `, threshold ${t.threshold * 100} %`}`);
  }
  if (tsdocReport) {
    mkdirSync(dirname(resolve(tsdocReport)), { recursive: true });
    writeFileSync(resolve(tsdocReport), `${JSON.stringify(tsdocReportRows(ref.components), null, 2)}\n`);
    log(`gen-component-docs: wrote ${tsdocReport}`);
  }
  let failed = false;
  if (tsdoc && !coverage.ok) {
    failed = true;
    if (!baseline) error(`gen-component-docs --tsdoc: no expiring baseline at ${TSDOC_BASELINE}`);
    for (const f of coverage.failures) error(`gen-component-docs --tsdoc: ${f.tier} TSDoc ${(f.ratio * 100).toFixed(1)} % < ${f.threshold * 100} % (${f.undocumented.length} undocumented, e.g. ${f.undocumented.slice(0, 5).join(', ')})`);
    if (coverage.stale.length) error(`gen-component-docs --tsdoc: stale baseline rows (now documented or removed): ${coverage.stale.join(', ')}`);
    if (coverage.expired.length) error(`gen-component-docs --tsdoc: expired baseline rows at ${version}: ${coverage.expired.join(', ')}`);
  }
  if (check) {
    const drift = diffPublic(root, rendered);
    if (drift.length) {
      error(`gen-component-docs --check: ${drift.length} page(s) out of date in ${PUBLIC_DIR} (types: ${ref.typesSource}):`);
      for (const d of drift) error(`  ${d.kind}: ${d.file}`);
      error('Run node scripts/docs/gen-component-docs.mjs and commit the result.');
      return 1;
    }
    log(`gen-component-docs --check: ${rendered.size} pages up to date (types: ${ref.typesSource})`);
    return failed ? 1 : 0;
  }
  let claims = null;
  const claimsPath = join(root, CLAIMS_PATH);
  if (existsSync(claimsPath)) claims = JSON.parse(readFileSync(claimsPath, 'utf8')).claims ?? null;
  const pub = join(root, PUBLIC_DIR); const pages = join(root, PAGES_DIR);
  rmSync(pages, { recursive: true, force: true });
  mkdirSync(pub, { recursive: true }); mkdirSync(pages, { recursive: true });
  for (const f of readdirSync(pub)) if (f.endsWith('.md') && !rendered.has(f)) rmSync(join(pub, f));
  for (const [file, text] of rendered) writeFileSync(join(pub, file), text);
  for (const c of ref.components) writeFileSync(join(pages, `${c.slug}.md`), renderPage(c, { claims }));
  writeFileSync(join(root, GENERATED_DIR, 'props.json'), serializeProps(ref.props));
  log(`gen-component-docs: ${rendered.size} pages, ${ref.skipped.length} metas without an export (types: ${ref.typesSource})`);
  return failed ? 1 : 0;
}

export function main(argv = process.argv.slice(2)) {
  const arg = (n) => { const i = argv.indexOf(n); return i >= 0 ? argv[i + 1] : null; };
  try {
    return run({
      check: argv.includes('--check'), tsdoc: argv.includes('--tsdoc'), tsdocReport: arg('--tsdoc-report'),
      tarball: arg('--tarball'), requirePacked: argv.includes('--require-packed'), snapshotPath: arg('--snapshot'),
    });
  } catch (err) {
    console.error(`gen-component-docs: ${err.message}`);
    return 1;
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) process.exit(main());
