#!/usr/bin/env node
/* gen-rsc-guide.mjs — PLAT-380 (REQ-PLAT-101). Writes the RSC guide
   apps/docs/content/guides/rsc.md from build/server-safe-exports.json
   (written by scripts/build/server-safe.mjs, REQ-PLAT-69) and
   build/exports.manifest.json. The whole page is generated: prose lives in
   this template, both tables come from the record, so the guide can never
   claim an entry or component is server-safe when the build gate says it is
   not.

   Usage:
     node scripts/docs/gen-rsc-guide.mjs --write   regenerate the page
     node scripts/docs/gen-rsc-guide.mjs --check   exit 1 when the committed page drifts
   Options: --record <path> --manifest <path> --out <path> (defaults below).
   A missing record is an error (exit 1), never an empty table. */
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
export const RECORD_PATH = 'build/server-safe-exports.json';
export const MANIFEST_PATH = 'build/exports.manifest.json';
export const RSC_GUIDE_PATH = 'apps/docs/content/guides/rsc.md';

const RSC_LABEL = {
  server: 'Server Component (renders in RSC, no client JS)',
  mixed: 'Mixed (server shell, client leaves)',
  client: "Client Component (`'use client'` leaf)",
};

const cell = (s) => String(s).replace(/\|/g, '\\|');
const sha256 = (text) => createHash('sha256').update(text).digest('hex');

/* Same split as scripts/build/lib/graph.mjs manifestEntries(): these sources
   are assets (CSS, JSON) with no module graph, so the record skips them. */
const ASSET_SOURCES = new Set(['build:css', 'build:deprecations', 'package.json']);

/** JS entry points of the manifest, in manifest order. */
export function manifestJsSubpaths(manifest) {
  return (manifest.entries ?? manifest).filter((e) => !ASSET_SOURCES.has(e.source)).map((e) => e.subpath);
}

/** Validate record ↔ manifest agreement; returns the list of problems. */
export function verifyRecord(record, manifest) {
  const problems = [];
  if (!record || record.version !== 1) problems.push('record.version must be 1');
  if (!Array.isArray(record?.entries)) problems.push('record.entries must be an array');
  if (!Array.isArray(record?.meta)) problems.push('record.meta must be an array');
  if (problems.length) return problems;
  const want = manifestJsSubpaths(manifest);
  const have = record.entries.map((e) => e.subpath);
  for (const s of want) if (!have.includes(s)) problems.push(`manifest entry ${s} missing from the record (re-run node scripts/build/server-safe.mjs --write)`);
  for (const s of have) if (!want.includes(s)) problems.push(`record entry ${s} is not a manifest JS entry`);
  for (const e of record.entries) if (typeof e.safe !== 'boolean') problems.push(`record entry ${e.subpath}: safe must be boolean`);
  return problems;
}

/** Rows of the entry-point table, in manifest order. */
export function entryRows(record, manifest) {
  const bySubpath = new Map(record.entries.map((e) => [e.subpath, e]));
  return manifestJsSubpaths(manifest).map((subpath) => {
    const e = bySubpath.get(subpath);
    const spec = subpath === '.' ? 'aura-glass' : `aura-glass/${subpath.slice(2)}`;
    return { subpath, specifier: spec, safe: e.safe, reason: e.reason ?? '' };
  });
}

/** Rows of the component table, sorted by name; undeclared rsc is reported, not guessed. */
export function componentRows(record) {
  /* server-safe.mjs falls back to the file name when a *.meta.ts declares no
     `name:` (not a ComponentMeta, e.g. a story matrix); those are not
     components and are left out of the table. */
  return record.meta.filter((m) => !/\.meta\.ts$/.test(m.name))
    .map((m) => ({ name: m.name, rsc: m.rsc ?? null }))
    .sort((a, b) => a.name.localeCompare(b.name));
}

export function renderRscGuide(recordText, manifest) {
  const record = JSON.parse(recordText);
  const problems = verifyRecord(record, manifest);
  if (problems.length) throw new Error(`gen-rsc-guide: ${problems.join('; ')}`);
  const entries = entryRows(record, manifest);
  const comps = componentRows(record);
  const lines = [
    '# Server Components',
    '',
    `Generated by \`node scripts/docs/gen-rsc-guide.mjs\` from \`${RECORD_PATH}\` (sha256 \`${sha256(recordText)}\`) and \`${MANIFEST_PATH}\`. Do not edit by hand: \`--check\` fails the docs build when this page drifts from the record.`,
    '',
    'AuraGlass ships no SSR provider, no styled-components registry and no client boundary wrapper. Interactive components are `\'use client\'` leaves, so you import them from a Server Component file like any other module: React renders the server parts on the server and hydrates only the leaves.',
    '',
    '## Rules',
    '',
    '- Import from the documented entry points only (`aura-glass`, `aura-glass/<subpath>`). Deep `dist/` imports are not part of the API.',
    '- `AuraGlassProvider` (from `aura-glass/theme`) is a client component. Render it from a small `\'use client\'` `providers.tsx` and wrap `{children}` with it in your root layout.',
    '- `AuraGlassScript` (from `aura-glass/theme`) is a Server Component. Render it as the first child of `<head>` so preferences apply before first paint.',
    '- Preferences (colour scheme, transparency, contrast, motion) stay user-owned: read them, never set them for the reader.',
    '- A component marked **Client** below needs no wrapper from you; it is already a client leaf. Pass it only serialisable props (no functions) from a Server Component, or render it from a client file when you need callbacks.',
    '',
    '## Entry points',
    '',
    'An entry point is server-safe when its module graph, followed under the `react-server` condition up to each `\'use client\'` boundary, reaches no browser global, no client hook and no SSR shim (REQ-PLAT-69 gate).',
    '',
    '| Import | Server-safe | Gate finding |',
    '|---|---|---|',
    ...entries.map((r) => `| \`${cell(r.specifier)}\` | ${r.safe ? 'yes' : 'no'} | ${r.reason ? cell(r.reason) : '—'} |`),
    '',
    '## Components',
    '',
    'From each component\'s `*.meta.ts` `rsc` field.',
    '',
    '| Component | Rendering |',
    '|---|---|',
    ...comps.map((c) => `| ${cell(c.name)} | ${c.rsc ? RSC_LABEL[c.rsc] ?? cell(c.rsc) : 'Not declared in its meta (treat as Client)'} |`),
    '',
  ];
  return lines.join('\n');
}

const arg = (name, fallback) => {
  const i = process.argv.indexOf(name);
  return i === -1 ? fallback : process.argv[i + 1];
};

export function main() {
  const mode = process.argv.includes('--write') ? 'write' : 'check';
  const recordPath = resolve(ROOT, arg('--record', RECORD_PATH));
  const manifestPath = resolve(ROOT, arg('--manifest', MANIFEST_PATH));
  const outPath = resolve(ROOT, arg('--out', RSC_GUIDE_PATH));
  if (!existsSync(recordPath)) {
    console.error(`gen-rsc-guide: ${recordPath} missing — it is written by node scripts/build/server-safe.mjs --write (REQ-PLAT-69).`);
    return 1;
  }
  const page = renderRscGuide(readFileSync(recordPath, 'utf8'), JSON.parse(readFileSync(manifestPath, 'utf8')));
  if (mode === 'write') {
    mkdirSync(dirname(outPath), { recursive: true });
    writeFileSync(outPath, page);
    console.log(`gen-rsc-guide: wrote ${outPath}`);
    return 0;
  }
  const current = existsSync(outPath) ? readFileSync(outPath, 'utf8') : null;
  if (current !== page) {
    console.error(`gen-rsc-guide: ${outPath} is stale — run node scripts/docs/gen-rsc-guide.mjs --write`);
    return 1;
  }
  console.log('gen-rsc-guide: up to date');
  return 0;
}

const isMain = process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href;
if (isMain) process.exitCode = main();
