#!/usr/bin/env node
// MAT-090: generate docs/motion.md. Every number in the tables is read from
// generated artifacts (src/motion/tokens.generated.ts, per-component
// *.meta.ts motion fields, motion-report.json when present) — nothing is
// hand-written (D-32). Regenerate: node scripts/docs/gen-motion-docs.mjs
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, walkFiles } from '../tokens/gates/_util.mjs';

const generated = readFileSync(join(ROOT, 'src/motion/tokens.generated.ts'), 'utf8');
const tokens = Object.fromEntries(
  [...generated.matchAll(/"((?:duration|ease|spring)\.[^"]+)":\s*("(?:[^"\\]|\\.)*"|\d+)/g)]
    .map(([, k, v]) => [k, v.startsWith('"') ? JSON.parse(v) : Number(v)]),
);
const spec = JSON.parse(readFileSync(join(ROOT, 'tokens/ref/time.tokens.json'), 'utf8')).ref?.time
  ?? JSON.parse(readFileSync(join(ROOT, 'tokens/ref/time.tokens.json'), 'utf8')).ref.time;
const springSpec = (name) => spec?.spring?.[name]?.$value ?? {};

// Component meta motion fields (component lanes land these as *.meta.ts).
const metaFiles = walkFiles(join(ROOT, 'src'), ['.meta.ts']);
const componentRows = [];
for (const f of metaFiles) {
  const text = readFileSync(f, 'utf8');
  const comp = /export\s+default\s+[{]|component:\s*['"]([\w-]+)['"]/.exec(text)?.[1]
    ?? f.split('/').pop().replace('.meta.ts', '');
  const motion = /motion\s*:\s*\{([^}]*)\}/s.exec(text)?.[1] ?? '';
  for (const m of motion.matchAll(/(\w+)\s*:\s*['"]([^'"]+)['"]/g))
    componentRows.push(`| ${comp} | ${m[1]} | \`${m[2]}\` |`);
}

const reportPath = join(ROOT, 'motion-report.json');
const report = existsSync(reportPath) ? JSON.parse(readFileSync(reportPath, 'utf8')) : null;

const row = (...cells) => `| ${cells.join(' | ')} |`;
const springName = (k) => k.replace('spring.', '').replace('-duration', '');
const stopCount = (linear) => (linear.match(/%|(?<=,)1\b/g) ?? []).length
  || linear.split(',').length - 1;

const doc = `<!-- @generated by scripts/docs/gen-motion-docs.mjs (MAT-090). Do not edit by hand. -->
# Motion

AuraGlass motion is spring-first: every enter/exit/press runs on a damped
spring compiled to a \`linear()\` easing at build time; durations and bezier
easings cover the few non-physical transitions. The tables below are generated
from \`src/motion/tokens.generated.ts\` — the numbers are never hand-maintained.

## Durations

${row('Token', 'ms', 'Use')}
${row('---', '---:', '---')}
${Object.entries(tokens)
  .filter(([k]) => k.startsWith('duration.'))
  .map(([k, v]) => row(`\`--ag-duration-${k.slice(9)}\``, v,
    k === 'duration.ambient' ? 'continuous-only (shimmer/lens drift)' : k.endsWith('-exit') ? 'exit transitions' : 'enter/state transitions'))
  .join('\n')}

## Easings

${row('Token', 'Cubic bezier')}
${row('---', '---')}
${Object.entries(tokens)
  .filter(([k]) => k.startsWith('ease.'))
  .map(([k, v]) => row(`\`--ag-ease-${k.slice(5)}\``, `\`${v}\``))
  .join('\n')}

## Springs (compiled \`linear()\`)

${row('Token', 'Settle (ms)', 'Stops', 'ζ', 'response (s)')}
${row('---', '---:', '---:', '---:', '---:')}
${[...new Set(Object.keys(tokens).filter((k) => k.startsWith('spring.') && !k.endsWith('-duration')))].map((k) => {
    const n = springName(k);
    const s = springSpec(n) ?? {};
    return row(`\`--ag-spring-${n}\``, tokens[`${k}-duration`], stopCount(tokens[k]),
      s.dampingRatio ?? '—', s.response?.value != null ? s.response.value / 1000 : '—');
  }).join('\n')}

Spring \`linear()\` curves carry per-stop progress hints; |x(t) − linear(t)| ≤ 0.005
over 1,000 samples vs the analytic damped solution (tests/tokens/motion-spring.test.ts).

## Component motion fields

Generated from each \`<Component>.meta.ts\` \`motion\` field.
${componentRows.length ? `\n${row('Component', 'Field', 'Value')}\n${row('---', '---', '---')}\n${componentRows.join('\n')}` : '\n_No component \`*.meta.ts\` motion fields are present yet — component lanes emit them; this table fills itself in on regenerate._'}

${report ? `## Motion report

Generated from \`motion-report.json\`:

\`\`\`json
${JSON.stringify(report, null, 1)}
\`\`\`
` : ''}
## Reduced motion

- \`data-ag-motion="calm|none"\` and \`prefers-reduced-motion: reduce\` zero all
  transform transitions (byte-identical springs across modes — MAT-044).
- Springs' settle durations stay readable: instant exits land at
  ${tokens['duration.instant-exit']}ms, never below.

## Manual screen-reader matrix (L13)

Run per row of the certification harness (REQ-MOT-118). Pass/fail per cell.

${row('AT / browser', 'Button', 'Dialog', 'Menu', 'Sheet', 'Tabs')}
${row('---', '---', '---', '---', '---', '---')}
${[
  'VoiceOver + Safari macOS (Reduce Motion)',
  'VoiceOver + Safari iOS (Reduce Motion)',
  'NVDA + Chrome (Show animations off)',
  'TalkBack + Chrome (Remove animations)',
].map((r) => row(r, '☐', '☐', '☐', '☐', '☐')).join('\n')}

## Human motion review (L14)

Sign-off checklist — reviewer records per-flagship verdicts in the PR:

- [ ] Specular response: highlight tracks pointer lift without lag or flutter.
- [ ] Materialization: glass cells blur-in/scale-in on the snappy spring (${tokens['spring.snappy-duration']}ms), never bounce.
- [ ] No press scale: press feedback is rim/glow + specular only (SC-38).
- [ ] Continuous ambient motion (${tokens['duration.ambient']}ms loop) invisible under \`prefers-reduced-motion\`.
`;

writeFileSync(join(ROOT, 'docs/motion.md'), doc);
console.log(`wrote docs/motion.md (${metaFiles.length} meta files, report: ${report ? 'yes' : 'no'})`);
