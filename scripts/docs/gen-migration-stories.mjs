#!/usr/bin/env node
// gen-migration-stories.mjs — PLAT-398. Emit .storybook/blocks-driven
// stories into stories/plat/migration/ and stories/plat/packaging/.
// Stories import ONLY from .storybook/blocks/index.tsx (the C0 seed's
// doc-page components) — they render deprecation + packaging tables, never
// component internals.
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const DEP = join(ROOT, 'deprecations.json');

const header = `/* generated by gen-migration-stories.mjs — do not edit */
import type { Meta, StoryObj } from '@storybook/react';
import { MigrationTable } from '../../../.storybook/blocks/index';
`;

export function main() {
  const rows = existsSync(DEP) ? (JSON.parse(readFileSync(DEP, 'utf8')).deprecations ?? []) : [];
  if (!rows.length) { console.warn('deprecations.json missing/empty (lane 1c) — migration stories pending'); return; }
  const dir = join(ROOT, 'stories/plat/migration');
  mkdirSync(dir, { recursive: true });
  for (const row of rows) {
    const id = row.id ?? row.key;
    const body = `const rows = ${JSON.stringify([row], null, 2)};\nconst meta: Meta = { title: 'plat/migration/${id}', parameters: { ag: { subject: 'migration-${id}', kind: 'docs' } } };\nexport default meta;\nexport const Default: StoryObj = { render: () => <MigrationTable rows={rows} /> };\n`;
    writeFileSync(join(dir, `${id}.stories.tsx`), header + body);
  }
  const pkgDir = join(ROOT, 'stories/plat/packaging');
  mkdirSync(pkgDir, { recursive: true });
  const manifest = join(ROOT, 'build/exports.manifest.json');
  if (existsSync(manifest)) {
    const entries = JSON.parse(readFileSync(manifest, 'utf8')).entries ?? [];
    writeFileSync(join(pkgDir, 'exports.stories.tsx'), header + `const rows = ${JSON.stringify(entries)};\nconst meta: Meta = { title: 'plat/packaging/exports', parameters: { ag: { subject: 'packaging-exports', kind: 'docs' } } };\nexport default meta;\nexport const Default: StoryObj = { render: () => <MigrationTable rows={rows} /> };\n`);
  }
  console.log(`migration stories: ${rows.length} + packaging`);
}
if (process.argv[1]?.endsWith('gen-migration-stories.mjs')) main();
