#!/usr/bin/env node
/* scripts/docs/gen-migration-stories.mjs — REQ-PLAT-105 (PLAT-398, REQ-FIN-43,
   FIN-C.3-11). One Storybook docs page per ComponentMeta that carries 4.x
   migration rows:

     stories/plat/migration/<Name>.generated.mdx   (committed)

   Each page renders only QUAL's S-51 blocks (`MigrationTable`, `SelectorTable`
   from .storybook/blocks/index.tsx, the one .storybook module MDX may import)
   over the component's own meta module, so the page never restates a name.

     node scripts/docs/gen-migration-stories.mjs           write (and prune stale pages)
     node scripts/docs/gen-migration-stories.mjs --check   exit 1 when any page is stale */
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, posix, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadMigrationMetas } from './lib/migration-guide.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
export const STORIES_DIR = 'stories/plat/migration';
const SUFFIX = '.generated.mdx';

/** MDX source of one page. `metaFile` is repo-relative (src/…/<Name>.meta.ts). */
export function storyMdx({ name, metaFile }) {
  const fromDir = STORIES_DIR;
  const metaImport = posix.relative(fromDir, metaFile.replace(/\.ts$/, ''));
  const blocks = posix.relative(fromDir, '.storybook/blocks/index');
  return `{/* GENERATED by scripts/docs/gen-migration-stories.mjs from ${metaFile} — do not edit. */}
import { Meta } from '@storybook/addon-docs/blocks';
import { MigrationTable, SelectorTable } from '${blocks}';
import meta from '${metaImport}';

<Meta title="Migration/${name}" />

# ${name}: migrating from 4.x

## Exports and props

<MigrationTable of={meta} />

## Selectors

<SelectorTable of={meta} />
`;
}

/** { '<Name>.generated.mdx': source } for every meta with migration rows. */
export async function pages(root = ROOT) {
  const metas = await loadMigrationMetas(root);
  const out = {};
  for (const m of metas.filter((x) => (x.migration ?? []).length).sort((a, b) => a.name.localeCompare(b.name))) {
    if (!/^[A-Z][A-Za-z0-9]*$/.test(m.name)) throw new Error(`${m.file}: meta name '${m.name}' is not a component name`);
    out[`${m.name}${SUFFIX}`] = storyMdx({ name: m.name, metaFile: m.file });
  }
  if (!Object.keys(out).length) throw new Error('gen-migration-stories: no ComponentMeta has migration rows');
  return out;
}

export async function main(argv = process.argv.slice(2), { root = ROOT } = {}) {
  const check = argv.includes('--check');
  const dir = join(root, STORIES_DIR);
  const want = await pages(root);
  const have = existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith(SUFFIX)) : [];
  const stale = [
    ...Object.entries(want).filter(([f, src]) => !existsSync(join(dir, f)) || readFileSync(join(dir, f), 'utf8') !== src).map(([f]) => f),
    ...have.filter((f) => !(f in want)),
  ];
  if (check) {
    if (stale.length) {
      console.error(`gen-migration-stories --check FAIL (run node scripts/docs/gen-migration-stories.mjs): ${stale.map((f) => posix.join(STORIES_DIR, f)).join(', ')}`);
      return 1;
    }
    console.log(`gen-migration-stories: ${Object.keys(want).length} pages verified`);
    return 0;
  }
  mkdirSync(dir, { recursive: true });
  for (const f of have) if (!(f in want)) rmSync(join(dir, f));
  for (const [f, src] of Object.entries(want)) writeFileSync(join(dir, f), src);
  console.log(`gen-migration-stories: ${Object.keys(want).length} pages written to ${relative(root, dir) || dir}`);
  return 0;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main().then((c) => process.exit(c)).catch((e) => { console.error(e); process.exit(1); });
}
