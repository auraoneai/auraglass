#!/usr/bin/env node
/**
 * gen-doctor-v5.mjs (REQ-PLAT-61): bundle @auraglass/cli's doctor checks and
 * v5 scan (packages/cli/src/doctor/standalone.ts) into the 4.x CLI as
 * bin/doctor-v5.generated.cjs, so `aura-glass doctor --v5` runs the
 * @auraglass/cli implementation unchanged instead of a reimplementation.
 *
 *   node scripts/ci/gen-doctor-v5.mjs           write the bundle
 *   node scripts/ci/gen-doctor-v5.mjs --check   exit 1 when the committed bundle is stale
 *
 * Uses the repo's pinned esbuild (devDependency); the output is deterministic
 * (no sourcemap, no banner timestamp, sorted metafile-free build).
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const ENTRY = path.join(ROOT, 'packages/cli/src/doctor/standalone.ts');
export const OUT = path.join(ROOT, 'bin/doctor-v5.generated.cjs');

const BANNER = [
  '/* GENERATED by scripts/ci/gen-doctor-v5.mjs from packages/cli/src/doctor/{checks,v5-core,standalone}.ts',
  '   (REQ-PLAT-61). Do not edit: change the @auraglass/cli sources and regenerate. */',
].join('\n');

export async function bundle() {
  const res = await build({
    entryPoints: [ENTRY],
    bundle: true,
    platform: 'node',
    format: 'cjs',
    target: 'node18',
    write: false,
    sourcemap: false,
    legalComments: 'none',
    banner: { js: BANNER },
    logLevel: 'silent',
  });
  return res.outputFiles[0].text;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = await bundle();
  if (process.argv.includes('--check')) {
    const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
    if (current !== text) {
      console.error(`gen-doctor-v5: ${path.relative(ROOT, OUT)} is stale — run node scripts/ci/gen-doctor-v5.mjs`);
      process.exit(1);
    }
    console.log('gen-doctor-v5: up to date');
  } else {
    writeFileSync(OUT, text);
    console.log(`gen-doctor-v5: wrote ${path.relative(ROOT, OUT)} (${text.length} bytes)`);
  }
}
